CACHE_DIR = Path(".cache/client-dashboard")

def load_prior_cache(slug):
    p = CACHE_DIR / f"{slug}.json"
    if p.exists():
        raw = json.loads(p.read_text())
        return {k: to_d(v) for k, v in raw.items()}
    return None

def save_cache(slug, kpis):
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    snapshot = {k: str(v["value"]) for k, v in kpis.items()}
    (CACHE_DIR / f"{slug}.json").write_text(json.dumps(snapshot, indent=2))

def build_cdc_rows(prior, current_kpis):
    """Return list of CDC row dicts."""
    rows = []
    for key, kpi in current_kpis.items():
        curr_val = kpi["value"]
        label = kpi["label"]
        if prior and key in prior:
            prior_val = prior[key]
            delta = (curr_val - prior_val).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
            if prior_val != 0:
                pct_chg = ((delta / prior_val) * 100).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
            else:
                pct_chg = Decimal("0")
            direction = "Improved" if delta > 0 else ("Declined" if delta < 0 else "Unchanged")
            rows.append({
                "label": label,
                "prior": str(prior_val),
                "current": str(curr_val),
                "delta": str(delta),
                "pct_change": str(pct_chg),
                "direction": direction,
            })
        else:
            rows.append({
                "label": label,
                "prior": "—",
                "current": str(curr_val),
                "delta": "—",
                "pct_change": "—",
                "direction": "First run",
            })
    return rows

