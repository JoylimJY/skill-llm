def main():
    parser = argparse.ArgumentParser(description="Client Dashboard KPI Report")
    parser.add_argument("--slug",    required=True,  help="Company slug")
    parser.add_argument("--month",   required=True,  help="Report month YYYY-MM")
    parser.add_argument("--out",     default=str(Path.home() / "Desktop"), help="Output directory")
    parser.add_argument("--sandbox", action="store_true", help="Use QBO sandbox")
    args = parser.parse_args()

    slug = args.slug
    month_str = args.month
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    if slug not in CLIENT_CONFIGS:
        print(f"ERROR: No config found for slug '{slug}'. Add to CLIENT_CONFIGS first.")
        sys.exit(1)

    config = CLIENT_CONFIGS[slug]
    print(f"Generating KPI Dashboard for {config['company_name']} — {month_str}")

    data = fetch_qbo_data(slug, month_str, sandbox=args.sandbox)
    kpis = compute_kpis(data, config, month_str)

    prior = load_prior_cache(slug)
    cdc_rows = build_cdc_rows(prior, kpis)

    wb = build_workbook(slug, month_str, config, kpis, cdc_rows, data)

    out_file = out_dir / f"KPI_Dashboard_{slug}_{month_str.replace('-', '_')}.xlsx"
    wb.save(str(out_file))
    save_cache(slug, kpis)

    print(f"Dashboard saved: {out_file}")
