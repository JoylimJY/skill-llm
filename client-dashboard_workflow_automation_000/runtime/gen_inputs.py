ARROW_MAP = [
    (15,  "↑↑"),
    (5,   "↑"),
    (2,   "↗"),
    (-2,  "→"),
    (-5,  "↘"),
    (-15, "↓"),
]

def pct_change_arrow(pct_val):
    """Map % change to direction arrow."""
    v = float(pct_val)
    for threshold, arrow in ARROW_MAP:
        if v >= threshold:
            return arrow
    return "↓↓"

BLOCK_CHARS = ["_", "▁", "▃", "▅", "▇", "█"]

def value_to_block(v, max_v, min_v):
    if max_v == min_v:
        return "▃"
    ratio_val = (float(v) - float(min_v)) / (float(max_v) - float(min_v))
    idx = min(int(ratio_val * (len(BLOCK_CHARS) - 1) + 0.5), len(BLOCK_CHARS) - 1)
    return BLOCK_CHARS[idx]

def build_sparkline(values_6mo):
    """Build arrow sparkline string from list of 6 Decimal values (oldest→newest)."""
    if len(values_6mo) < 2:
        return "→"
    arrows = []
    for i in range(1, len(values_6mo)):
        prev = values_6mo[i-1]
        curr = values_6mo[i]
        if prev == 0:
            arrows.append("→")
        else:
            chg = mom_growth(curr, prev)
            arrows.append(pct_change_arrow(chg))
    return " ".join(arrows)

def build_block_sparkline(values_6mo):
    """Build block-char sparkline from list of 6 Decimal values."""
    if not values_6mo:
        return "_"
    max_v = max(float(v) for v in values_6mo)
    min_v = min(float(v) for v in values_6mo)
    return "".join(value_to_block(v, max_v, min_v) for v in values_6mo)

