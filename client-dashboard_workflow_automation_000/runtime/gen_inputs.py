def score_kpi(key, value, config):
    thresholds = config.get("thresholds", {})
    if key not in thresholds:
        return NA
    t = thresholds[key]
    green_lo, green_hi = t["green"]
    yellow_lo, yellow_hi = t["yellow"]

    def in_band(lo, hi, v):
        lo_ok = (lo is None) or (v >= lo)
        hi_ok = (hi is None) or (v <= hi)
        return lo_ok and hi_ok

    if in_band(green_lo, green_hi, value):
        return GREEN
    elif in_band(yellow_lo, yellow_hi, value):
        return YELLOW
    else:
        return RED

def score_fill(score):
    return {GREEN: FILL_GREEN, YELLOW: FILL_YELLOW, RED: FILL_RED, NA: FILL_GREY}[score]

