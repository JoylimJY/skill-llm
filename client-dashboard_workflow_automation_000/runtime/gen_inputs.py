def to_d(v):
    """Convert any numeric to Decimal safely."""
    try:
        return Decimal(str(v))
    except InvalidOperation:
        return Decimal("0")

def pct(numerator, denominator):
    if denominator == 0:
        return Decimal("0")
    return (to_d(numerator) / to_d(denominator) * 100).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)

def ratio(numerator, denominator):
    if denominator == 0:
        return Decimal("0")
    return (to_d(numerator) / to_d(denominator)).quantize(Decimal("0.0001"), rounding=ROUND_HALF_UP)

def mom_growth(curr, prior):
    if prior == 0:
        return Decimal("0")
    return ((to_d(curr) - to_d(prior)) / to_d(prior) * 100).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)

