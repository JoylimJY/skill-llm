#!/usr/bin/env python3
"""
Evaluation script for the office-hub cross-document pipeline task.
Checks that:
1. quarterly_sales.xlsx exists and was generated via create_excel.py (has _meta sheet, Summary sheet, gold header)
2. sales_report.docx exists and was generated via create_word.py (correct author/subject, has table, attribution line, Key Statistics section)
3. The pipeline is end-to-end correct (Word doc references data from the Excel file)
"""

import sys
import json
from pathlib import Path

def run_eval(workspace: str):
    ws = Path(workspace)
    checks = []
    total_score = 0.0
    max_score = 7

    # ── Helper ─────────────────────────────────────────────────────────────
    def add_check(name, passed, detail, weight=1):
        checks.append({"name": name, "passed": passed, "detail": detail})
        return weight if passed else 0

    # ── FIND FILES ──────────────────────────────────────────────────────────
    xlsx_files = list(ws.rglob("quarterly_sales.xlsx"))
    docx_files = list(ws.rglob("sales_report.docx"))

    xlsx_path = xlsx_files[0] if xlsx_files else None
    docx_path = docx_files[0] if docx_files else None

    # Check 1: Excel file exists
    total_score += add_check(
        "quarterly_sales.xlsx exists",
        xlsx_path is not None,
        f"Found at: {xlsx_path}" if xlsx_path else "File not found in workspace"
    )

    # Check 2: Word file exists
    total_score += add_check(
        "sales_report.docx exists",
        docx_path is not None,
        f"Found at: {docx_path}" if docx_path else "File not found in workspace"
    )

    # ── EXCEL CHECKS ────────────────────────────────────────────────────────
    if xlsx_path and xlsx_path.exists():
        try:
            import openpyxl
            wb = openpyxl.load_workbook(xlsx_path)

            # Check 3: _meta hidden sheet with office-hub-v3 signature
            has_meta = "_meta" in wb.sheetnames
            if has_meta:
                ws_meta = wb["_meta"]
                gen_val = ws_meta["B1"].value
                script_val = ws_meta["B2"].value
                meta_ok = (gen_val == "office-hub-v3" and script_val == "create_excel.py")
                detail = f"_meta B1={gen_val}, B2={script_val}"
            else:
                meta_ok = False
                detail = "No _meta sheet found — file was NOT generated by create_excel.py"

            total_score += add_check(
                "Excel has _meta sheet with office-hub-v3 signature",
                meta_ok,
                detail,
                weight=1
            )

            # Check 4: Summary sheet exists with correct structure
            has_summary = "Summary" in wb.sheetnames
            if has_summary:
                ws_sum = wb["Summary"]
                label_a1 = ws_sum["A1"].value
                val_b1 = ws_sum["B1"].value
                label_a4 = ws_sum["A4"].value
                val_b4 = ws_sum["B4"].value
                summary_ok = (
                    label_a1 == "Total Rows" and
                    isinstance(val_b1, int) and val_b1 == 15 and
                    label_a4 == "Sum Revenue" and
                    val_b4 is not None and abs(float(val_b4) - 919147.5) < 1.0
                )
                detail = (
                    f"Summary: Total Rows={val_b1}, Sum Revenue={val_b4} "
                    f"(expected 15 rows, 919147.5 revenue)"
                )
            else:
                summary_ok = False
                detail = "No Summary sheet — --add-summary flag was not used"

            total_score += add_check(
                "Excel has Summary sheet with correct aggregates (--add-summary used)",
                summary_ok,
                detail,
                weight=2  # weighted more — key proprietary flag
            )

            # Check 5: Data sheet has gold header fill
            data_sheet_name = None
            for name in wb.sheetnames:
                if name not in ("_meta", "Summary"):
                    data_sheet_name = name
                    break
            if data_sheet_name:
                ws_data = wb[data_sheet_name]
                header_cell = ws_data.cell(row=1, column=1)
                fill = header_cell.fill
                fill_color = fill.fgColor.rgb if fill and fill.fgColor else None
                gold_ok = fill_color is not None and fill_color.upper() in ("FFFFD700", "FFD700")
                detail = f"Header cell fill color: {fill_color} (expected FFD700/FFFFD700)"
            else:
                gold_ok = False
                detail = "No data sheet found"

            total_score += add_check(
                "Excel data sheet has gold (FFD700) header row from create_excel.py",
                gold_ok,
                detail
            )

        except Exception as e:
            checks.append({"name": "Excel file parsing", "passed": False, "detail": f"Exception: {e}"})
    else:
        # Add placeholder failed checks
        for name in [
            "Excel has _meta sheet with office-hub-v3 signature",
            "Excel has Summary sheet with correct aggregates (--add-summary used)",
            "Excel data sheet has gold (FFD700) header row from create_excel.py"
        ]:
            checks.append({"name": name, "passed": False, "detail": "Excel file missing"})

    # ── WORD CHECKS ─────────────────────────────────────────────────────────
    if docx_path and docx_path.exists():
        try:
            from docx import Document
            from docx.shared import RGBColor

            doc = Document(docx_path)
            cp = doc.core_properties

            # Check 6: Document properties set by create_word.py
            author_ok = cp.author == "office-hub-v3"
            subject_ok = cp.subject == "office-hub-automated-report"
            props_ok = author_ok and subject_ok
            detail = f"author='{cp.author}' subject='{cp.subject}'"
            total_score += add_check(
                "Word doc has office-hub-v3 author/subject properties",
                props_ok,
                detail,
                weight=1
            )

            # Check 7: "Generated by office-hub-v3" attribution paragraph in italic gray
            attr_found = False
            attr_detail = "Attribution paragraph not found"
            for para in doc.paragraphs:
                if "Generated by office-hub-v3" in para.text:
                    for run in para.runs:
                        if "Generated by office-hub-v3" in run.text:
                            if run.italic and run.font.color.rgb == RGBColor(0x96, 0x96, 0x96):
                                attr_found = True
                                attr_detail = "Found italic gray attribution paragraph"
                            elif run.italic:
                                attr_found = True
                                attr_detail = f"Found italic attribution (color={run.font.color.rgb})"
                            else:
                                attr_detail = f"Found attribution but italic={run.italic}"
                    break

            total_score += add_check(
                "Word doc has 'Generated by office-hub-v3' italic attribution line",
                attr_found,
                attr_detail,
                weight=1
            )

            # Check 8: Word doc has "Key Statistics" heading (--include-summary used)
            ks_found = any("Key Statistics" in p.text for p in doc.paragraphs)
            bullet_found = any(
                "Total Rows" in p.text or "Sum Revenue" in p.text
                for p in doc.paragraphs
            )
            ks_ok = ks_found and bullet_found
            detail = f"Key Statistics heading={ks_found}, bullet stats={bullet_found}"
            total_score += add_check(
                "Word doc has Key Statistics section from Summary sheet (--include-summary used)",
                ks_ok,
                detail,
                weight=2  # weighted — requires chained Excel→Word pipeline with summary
            )

            # Check 9: Word doc has a data table
            table_ok = len(doc.tables) > 0
            if table_ok:
                tbl = doc.tables[0]
                row_count = len(tbl.rows)
                detail = f"Table found with {row_count} rows"
            else:
                detail = "No tables found in Word document"
            total_score += add_check(
                "Word doc contains data table",
                table_ok,
                detail,
                weight=1
            )

        except Exception as e:
            checks.append({"name": "Word file parsing", "passed": False, "detail": f"Exception: {e}"})
    else:
        for name in [
            "Word doc has office-hub-v3 author/subject properties",
            "Word doc has 'Generated by office-hub-v3' italic attribution line",
            "Word doc has Key Statistics section from Summary sheet (--include-summary used)",
            "Word doc contains data table"
        ]:
            checks.append({"name": name, "passed": False, "detail": "Word file missing"})

    # ── FINAL SCORE ─────────────────────────────────────────────────────────
    # Recount from checks with weights baked in
    # (weights were added directly to total_score above)
    normalized = round(total_score / max_score, 3)
    overall_passed = normalized >= 0.85  # must pass at least 85%

    return {
        "passed": overall_passed,
        "score": normalized,
        "checks": checks
    }


if __name__ == "__main__":
    workspace = sys.argv[1] if len(sys.argv) > 1 else "/workspace"
    result = run_eval(workspace)
    print(json.dumps(result, indent=2))