def find_stocks_for_query(query):
    """Find best matching stocks for a query string"""
    query_lower = query.lower()
    # Try exact match first
    for key, stocks in MOCK_STOCKS.items():
        if key in query:
            return stocks
    # Try partial match
    for key, stocks in MOCK_STOCKS.items():
        if any(char in query for char in key):
            return stocks
    # Default fallback
    return MOCK_STOCKS["充电桩"]

@app.route('/iwencai/query', methods=['GET', 'POST'])
def query():
    """Main query endpoint"""
    if request.method == 'POST':
        data = request.get_json() or {}
        q = data.get('query', data.get('question', data.get('q', '')))
    else:
        q = request.args.get('query', request.args.get('question', request.args.get('q', '')))
    
    stocks = find_stocks_for_query(q)
    return jsonify({
        "status": 0,
        "message": "success",
        "data": {
            "answer": stocks,
            "total": len(stocks),
            "query": q
        }
    })

@app.route('/search', methods=['GET', 'POST'])
def search():
    """Alternative search endpoint"""
    if request.method == 'POST':
        data = request.get_json() or {}
        q = data.get('query', data.get('question', data.get('q', '')))
    else:
        q = request.args.get('query', request.args.get('question', request.args.get('q', '')))
    
    stocks = find_stocks_for_query(q)
    return jsonify({
        "status": "ok",
        "result": stocks,
        "count": len(stocks)
    })

