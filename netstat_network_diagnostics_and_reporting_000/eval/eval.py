#!/usr/bin/env python3
"""
Evaluation script for the network audit task.
Checks that the agent:
1. Ran the listen command (data file exists in ~/.local/share/netstat/)
2. Ran the connections ESTABLISHED command (data file exists)
3. Ran the stats command (data file exists)
4. Produced a network_audit_report.json with correct, script-derived values
"""

import sys
import json
import os
from pathlib import Path

def main():
    workspace = sys.argv[1] if len(sys.argv) > 1 else "/workspace"
    home = os.path.expanduser("~")
    datadir = Path(home) / ".local" / "share" / "netstat"

    checks = []
    overall_passed = True

    # ── Check 1: listen.txt was generated by the script ──────────────────────
    listen_file = datadir / "listen.txt"
    try:
        listen_content = listen_file.read_text()
        has_listen_ports = (
            "22" in listen_content and
            "80" in listen_content and
            "443" in listen_content and
            "5432" in listen_content and
            "8080" in listen_content
        )
        c1_passed = has_listen_ports
        c1_detail = (
            f"listen.txt exists with expected ports: {has_listen_ports}"
            if c1_passed
            else f"listen.txt missing expected ports. Content: {listen_content[:300]}"
        )
    except Exception as e:
        c1_passed = False
        c1_detail = f"listen.txt not found or unreadable: {e}"
    checks.append({"name": "listen_command_executed", "passed": c1_passed, "detail": c1_detail})
    if not c1_passed:
        overall_passed = False

    # ── Check 2: connections_ESTABLISHED.txt was generated ───────────────────
    conn_file = datadir / "connections_ESTABLISHED.txt"
    try:
        conn_content = conn_file.read_text()
        # Must contain the 4 ESTABLISHED entries from our mock
        has_established = (
            "ESTABLISHED" in conn_content and
            "54321" in conn_content and
            "54322" in conn_content and
            "60001" in conn_content and
            "45001" in conn_content
        )
        c2_passed = has_established
        c2_detail = (
            "connections_ESTABLISHED.txt exists with all 4 ESTABLISHED connections"
            if c2_passed
            else f"connections_ESTABLISHED.txt missing entries. Content: {conn_content[:300]}"
        )
    except Exception as e:
        c2_passed = False
        c2_detail = f"connections_ESTABLISHED.txt not found or unreadable: {e}"
    checks.append({"name": "connections_established_command_executed", "passed": c2_passed, "detail": c2_detail})
    if not c2_passed:
        overall_passed = False

    # ── Check 3: stats.txt was generated ─────────────────────────────────────
    stats_file = datadir / "stats.txt"
    try:
        stats_content = stats_file.read_text()
        has_stats = (
            "1024" in stats_content and
            "512" in stats_content and
            "retransmitted" in stats_content
        )
        c3_passed = has_stats
        c3_detail = (
            "stats.txt exists with expected network statistics"
            if c3_passed
            else f"stats.txt missing expected data. Content: {stats_content[:300]}"
        )
    except Exception as e:
        c3_passed = False
        c3_detail = f"stats.txt not found or unreadable: {e}"
    checks.append({"name": "stats_command_executed", "passed": c3_passed, "detail": c3_detail})
    if not c3_passed:
        overall_passed = False

    # ── Check 4: network_audit_report.json exists ─────────────────────────────
    report_candidates = list(Path(workspace).rglob("network_audit_report.json"))
    if not report_candidates:
        checks.append({
            "name": "report_file_exists",
            "passed": False,
            "detail": "network_audit_report.json not found anywhere under workspace"
        })
        overall_passed = False
        # Skip further checks
        score = sum(1 for c in checks if c["passed"]) / 6.0
        print(json.dumps({"passed": False, "score": score, "checks": checks}))
        return

    report_path = report_candidates[0]
    checks.append({
        "name": "report_file_exists",
        "passed": True,
        "detail": f"Found at {report_path}"
    })

    # ── Check 5: report is valid JSON ─────────────────────────────────────────
    try:
        report = json.loads(report_path.read_text())
        c5_passed = isinstance(report, dict)
        c5_detail = "Valid JSON object" if c5_passed else "JSON parsed but not a dict"
    except Exception as e:
        report = None
        c5_passed = False
        c5_detail = f"Invalid JSON: {e}"
    checks.append({"name": "report_is_valid_json", "passed": c5_passed, "detail": c5_detail})
    if not c5_passed:
        overall_passed = False

    if report is None:
        score = sum(1 for c in checks if c["passed"]) / 6.0
        print(json.dumps({"passed": False, "score": score, "checks": checks}))
        return

    # ── Check 6: report contains correct listening ports from script output ───
    try:
        # The report must include listening ports matching what the script wrote
        listen_ports_in_report = False

        def find_ports(obj, depth=0):
            """Recursively search for port numbers in any structure."""
            if depth > 10:
                return False
            if isinstance(obj, dict):
                for k, v in obj.items():
                    if find_ports(v, depth+1):
                        return True
            elif isinstance(obj, list):
                for item in obj:
                    if find_ports(item, depth+1):
                        return True
            elif isinstance(obj, (str, int)):
                s = str(obj)
                # Must have at least 4 of the 6 expected listening ports/services
                expected = ["22", "80", "443", "5432", "8080", "9090"]
                found = sum(1 for p in expected if p in s)
                if found >= 4:
                    return True
            return False

        # Check top-level for a listening_ports key or similar
        report_str = json.dumps(report)
        expected_ports = ["22", "80", "443", "5432", "8080"]
        ports_found = sum(1 for p in expected_ports if p in report_str)
        listen_ports_in_report = ports_found >= 4

        c6_passed = listen_ports_in_report
        c6_detail = (
            f"Report contains {ports_found}/5 expected listening port numbers (22,80,443,5432,8080)"
        )
    except Exception as e:
        c6_passed = False
        c6_detail = f"Error checking listening ports in report: {e}"
    checks.append({"name": "report_contains_listening_ports", "passed": c6_passed, "detail": c6_detail})
    if not c6_passed:
        overall_passed = False

    # ── Check 7: report contains ESTABLISHED connection count (should be 4) ───
    try:
        report_str = json.dumps(report)
        # The mock has exactly 4 ESTABLISHED connections
        # We look for the number 4 in the context of "established" key or field
        established_ok = False

        def search_established(obj):
            if isinstance(obj, dict):
                for k, v in obj.items():
                    kl = str(k).lower()
                    if "establish" in kl or "connection" in kl:
                        if isinstance(v, (int, float)) and int(v) == 4:
                            return True
                        if isinstance(v, list) and len(v) == 4:
                            return True
                    if search_established(v):
                        return True
            elif isinstance(obj, list):
                for item in obj:
                    if search_established(item):
                        return True
            return False

        established_ok = search_established(report)

        # Fallback: look for string "4" near "established" in raw JSON
        if not established_ok:
            import re
            # Find if "4" appears as a value when a key mentions "establish"
            # Or if there's a list of 4 established connections
            lower_str = report_str.lower()
            # Check for 4 occurrences of "established" (one per connection entry)
            if lower_str.count("established") >= 4:
                established_ok = True

        c7_passed = established_ok
        c7_detail = (
            "Report correctly reflects 4 ESTABLISHED connections from script output"
            if c7_passed
            else "Report does not appear to contain the 4 ESTABLISHED connections from script output"
        )
    except Exception as e:
        c7_passed = False
        c7_detail = f"Error checking ESTABLISHED connections in report: {e}"
    checks.append({"name": "report_contains_established_connections", "passed": c7_passed, "detail": c7_detail})
    if not c7_passed:
        overall_passed = False

    # ── Check 8: report contains stats data derived from script ──────────────
    try:
        report_str = json.dumps(report)
        # Must contain at least one key stat: 1024 (total packets), 512 (active), 2 (retransmitted)
        stats_ok = "1024" in report_str or "retransmit" in report_str.lower() or "segment" in report_str.lower()
        c8_passed = stats_ok
        c8_detail = (
            "Report contains network statistics data from stats command"
            if c8_passed
            else "Report does not appear to contain network statistics from the stats command"
        )
    except Exception as e:
        c8_passed = False
        c8_detail = f"Error checking stats in report: {e}"
    checks.append({"name": "report_contains_network_stats", "passed": c8_passed, "detail": c8_detail})
    if not c8_passed:
        overall_passed = False

    # ── Final scoring ─────────────────────────────────────────────────────────
    num_passed = sum(1 for c in checks if c["passed"])
    score = num_passed / len(checks)
    overall_passed = overall_passed and (score >= 0.75)

    print(json.dumps({
        "passed": overall_passed,
        "score": round(score, 3),
        "checks": checks
    }, indent=2))


if __name__ == "__main__":
    main()