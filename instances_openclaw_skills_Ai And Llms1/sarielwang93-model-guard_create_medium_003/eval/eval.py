import json
import os
import re
import sys
from pathlib import Path

workspace = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('.')
checks = []


def add_check(name, passed, detail):
    checks.append({"name": name, "passed": bool(passed), "detail": str(detail)})


def safe_read(path):
    try:
        return path.read_text(encoding='utf-8', errors='replace')
    except Exception as e:
        return None, e

# Check 1: required output file exists
try:
    guard_path = workspace / 'guard.js'
    exists = guard_path.exists()
    add_check('guard_script_exists', exists, 'guard.js found' if exists else 'guard.js is missing')
except Exception as e:
    add_check('guard_script_exists', False, f'Error checking guard.js: {e}')

# Check 2: status files generated by inputs
for fname in ['status.json', 'status.txt']:
    try:
        p = workspace / fname
        if not p.exists():
            add_check(f'{fname}_exists', False, f'{fname} is missing')
            continue
        content = p.read_text(encoding='utf-8', errors='replace')
        marker_ok = 'MODEL_GUARD_MARKER_7XQ2'.lower() in content.lower()
        add_check(f'{fname}_marker', marker_ok, 'marker found' if marker_ok else 'marker not found')
    except Exception as e:
        add_check(f'{fname}_marker', False, f'Error reading {fname}: {e}')

# Check 3: guard.js contains expected key ideas, using forgiving matching
try:
    text = (workspace / 'guard.js').read_text(encoding='utf-8', errors='replace') if (workspace / 'guard.js').exists() else ''
    lowered = re.sub(r'\s+', ' ', text.lower())
    ok_threshold = 'threshold' in lowered
    ok_fallback = 'fallback_model' in lowered or 'fallback model' in lowered
    ok_candidates = 'candidates' in lowered
    add_check('guard_logic_mentions_threshold', ok_threshold, 'threshold mention present' if ok_threshold else 'threshold mention missing')
    add_check('guard_logic_mentions_fallback', ok_fallback, 'fallback mention present' if ok_fallback else 'fallback mention missing')
    add_check('guard_logic_mentions_candidates', ok_candidates, 'candidates mention present' if ok_candidates else 'candidates mention missing')
except Exception as e:
    add_check('guard_logic_mentions_threshold', False, f'Error inspecting guard.js: {e}')
    add_check('guard_logic_mentions_fallback', False, f'Error inspecting guard.js: {e}')
    add_check('guard_logic_mentions_candidates', False, f'Error inspecting guard.js: {e}')

# Check 4: status.json parses and has marker/default model
try:
    p = workspace / 'status.json'
    if not p.exists():
        add_check('status_json_valid', False, 'status.json missing')
    else:
        try:
            obj = json.loads(p.read_text(encoding='utf-8', errors='replace'))
            default_model = (((obj or {}).get('defaults') or {}).get('model') or {}).get('primary', '')
            marker = str(obj.get('marker', ''))
            add_check('status_json_valid', True, 'status.json parsed successfully')
            add_check('status_json_default_model', 'sonnet' in default_model.lower(), f'default model: {default_model}')
            add_check('status_json_marker', 'MODEL_GUARD_MARKER_7XQ2'.lower() in marker.lower(), f'marker: {marker}')
        except Exception as e:
            add_check('status_json_valid', False, f'Could not parse status.json: {e}')
            add_check('status_json_default_model', False, 'skipped due to parse failure')
            add_check('status_json_marker', False, 'skipped due to parse failure')
except Exception as e:
    add_check('status_json_valid', False, f'Error checking status.json: {e}')

# Final scoring
try:
    total = len(checks)
    passed = sum(1 for c in checks if c['passed'])
    score = passed / total if total else 0.0
    result = {"passed": passed == total and total > 0, "score": score, "checks": checks}
    print(json.dumps(result, ensure_ascii=False))
except Exception:
    print(json.dumps({"passed": False, "score": 0.0, "checks": [{"name": "fatal_error", "passed": False, "detail": "Unexpected error in evaluator"}]}))
