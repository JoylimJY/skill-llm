#!/usr/bin/env python3
"""
Evaluation script for the dotline-art task.

Checks:
1. Both banner files exist (nihao_shijie_banner.txt and devops_banner.txt).
2. The Chinese text banner (你好世界 -> NIHAOSHIJIE) uses pinyin conversion
   (no Chinese characters in output, contains dot-line art characters).
3. The DEVOPS banner contains valid dot-line art characters.
4. Both outputs match what the actual script produces (ground-truth comparison).
5. The outputs were NOT generated by figlet/pyfiglet (wrong format check).
"""

import sys
import json
import subprocess
from pathlib import Path

def run_script(text: str) -> str:
    """Run the reference dotline_art.py and capture output."""
    script = Path("/workspace/skills/dotline-art/scripts/dotline_art.py")
    result = subprocess.run(
        ["python3", str(script), text],
        capture_output=True, text=True, timeout=15
    )
    return result.stdout.strip()

def find_banner_file(workspace: Path, patterns: list) -> Path | None:
    """Search for a file matching any of the given glob patterns."""
    for pattern in patterns:
        matches = list(workspace.rglob(pattern))
        if matches:
            return matches[0]
    return None

def check_dotline_style(content: str) -> bool:
    """Check that content looks like dot-line art (uses . - | / \\ ' characters in patterns)."""
    dotline_chars = set(".-|/\\'`")
    lines = [l for l in content.splitlines() if l.strip()]
    if len(lines) < 5:
        return False
    char_count = sum(1 for c in content if c in dotline_chars)
    return char_count > 10

def check_no_chinese(content: str) -> bool:
    """Ensure no Chinese characters remain in the output."""
    for char in content:
        if '\u4e00' <= char <= '\u9fff':
            return False
    return True

def normalize(s: str) -> str:
    return '\n'.join(line.rstrip() for line in s.strip().splitlines())

checks = []
score = 0.0
workspace = Path(sys.argv[1])

# ── Ground truth ─────────────────────────────────────────────────────────────
try:
    gt_chinese = run_script("你好世界")
    gt_devops  = run_script("DEVOPS")
except Exception as e:
    print(json.dumps({
        "passed": False, "score": 0.0,
        "checks": [{"name": "script_execution", "passed": False, "detail": str(e)}]
    }))
    sys.exit(0)

# ── Check 1: nihao_shijie_banner.txt exists ───────────────────────────────────
banner_chinese_file = find_banner_file(workspace, [
    "nihao_shijie_banner.txt",
    "nihaoshijie_banner.txt",
    "nihao_banner.txt",
    "chinese_banner.txt",
])
c1_passed = banner_chinese_file is not None
checks.append({
    "name": "chinese_banner_file_exists",
    "passed": c1_passed,
    "detail": f"Found at {banner_chinese_file}" if c1_passed else "File not found (expected nihao_shijie_banner.txt or similar)"
})

# ── Check 2: devops_banner.txt exists ────────────────────────────────────────
banner_devops_file = find_banner_file(workspace, [
    "devops_banner.txt",
    "DEVOPS_banner.txt",
    "devops_art.txt",
])
c2_passed = banner_devops_file is not None
checks.append({
    "name": "devops_banner_file_exists",
    "passed": c2_passed,
    "detail": f"Found at {banner_devops_file}" if c2_passed else "File not found (expected devops_banner.txt or similar)"
})

# ── Check 3: Chinese banner has no Chinese characters & is dot-line style ────
if c1_passed:
    try:
        content = banner_chinese_file.read_text(encoding="utf-8")
        no_chinese = check_no_chinese(content)
        is_dotline = check_dotline_style(content)
        c3_passed = no_chinese and is_dotline
        detail = f"no_chinese={no_chinese}, is_dotline_style={is_dotline}"
    except Exception as e:
        c3_passed = False
        detail = str(e)
else:
    c3_passed = False
    detail = "Skipped: file missing"
checks.append({
    "name": "chinese_banner_pinyin_and_dotline",
    "passed": c3_passed,
    "detail": detail
})

# ── Check 4: DEVOPS banner is dot-line style ──────────────────────────────────
if c2_passed:
    try:
        content_d = banner_devops_file.read_text(encoding="utf-8")
        c4_passed = check_dotline_style(content_d)
        detail4 = f"is_dotline_style={c4_passed}, lines={len(content_d.splitlines())}"
    except Exception as e:
        c4_passed = False
        detail4 = str(e)
else:
    c4_passed = False
    detail4 = "Skipped: file missing"
checks.append({
    "name": "devops_banner_dotline_style",
    "passed": c4_passed,
    "detail": detail4
})

# ── Check 5: Chinese banner matches ground truth ──────────────────────────────
if c1_passed:
    try:
        content_c = banner_chinese_file.read_text(encoding="utf-8")
        c5_passed = normalize(content_c) == normalize(gt_chinese)
        detail5 = "Exact match" if c5_passed else f"Content mismatch.\nExpected:\n{gt_chinese[:200]}\nGot:\n{content_c[:200]}"
    except Exception as e:
        c5_passed = False
        detail5 = str(e)
else:
    c5_passed = False
    detail5 = "Skipped: file missing"
checks.append({
    "name": "chinese_banner_exact_match",
    "passed": c5_passed,
    "detail": detail5
})

# ── Check 6: DEVOPS banner matches ground truth ───────────────────────────────
if c2_passed:
    try:
        content_d2 = banner_devops_file.read_text(encoding="utf-8")
        c6_passed = normalize(content_d2) == normalize(gt_devops)
        detail6 = "Exact match" if c6_passed else f"Content mismatch.\nExpected:\n{gt_devops[:200]}\nGot:\n{content_d2[:200]}"
    except Exception as e:
        c6_passed = False
        detail6 = str(e)
else:
    c6_passed = False
    detail6 = "Skipped: file missing"
checks.append({
    "name": "devops_banner_exact_match",
    "passed": c6_passed,
    "detail": detail6
})

# ── Check 7: Outputs not from figlet/pyfiglet (figlet produces _ patterns) ────
figlet_indicators = ["_", "(__", "|__"]
all_content = ""
if c1_passed:
    try:
        all_content += banner_chinese_file.read_text(encoding="utf-8")
    except:
        pass
if c2_passed:
    try:
        all_content += banner_devops_file.read_text(encoding="utf-8")
    except:
        pass
c7_passed = not any(ind in all_content for ind in figlet_indicators)
checks.append({
    "name": "not_figlet_style",
    "passed": c7_passed,
    "detail": "Output does not appear to be figlet-generated" if c7_passed else "Output looks like figlet (found _ or |__ patterns)"
})

# ── Scoring ───────────────────────────────────────────────────────────────────
weights = [0.10, 0.10, 0.15, 0.15, 0.20, 0.20, 0.10]
score = sum(w for w, c in zip(weights, checks) if c["passed"])
passed = all(c["passed"] for c in checks)

print(json.dumps({
    "passed": passed,
    "score": round(score, 3),
    "checks": checks
}, ensure_ascii=False, indent=2))