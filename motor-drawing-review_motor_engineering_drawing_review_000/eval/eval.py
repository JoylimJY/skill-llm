import sys
import json
import re
from pathlib import Path

def evaluate(workspace: str):
    checks = []
    
    # =========================================================
    # CHECK 0: review_full.txt must exist (agent ran the checklist script)
    # =========================================================
    checklist_files = list(Path(workspace).rglob("review_full.txt"))
    checklist_exists = len(checklist_files) > 0
    checklist_content = ""
    if checklist_exists:
        try:
            checklist_content = checklist_files[0].read_text(encoding="utf-8")
        except Exception as e:
            checklist_content = ""
    
    checks.append({
        "name": "review_full.txt generated by checklist script",
        "passed": checklist_exists and "完整审图清单" in checklist_content,
        "detail": f"Found {len(checklist_files)} file(s). Content snippet: {checklist_content[:80]!r}" if checklist_files else "File not found"
    })

    # =========================================================
    # CHECK 1: review_report.md must exist
    # =========================================================
    report_files = list(Path(workspace).rglob("review_report.md"))
    report_exists = len(report_files) > 0
    report_content = ""
    if report_exists:
        try:
            report_content = report_files[0].read_text(encoding="utf-8")
        except Exception as e:
            report_content = ""
            checks.append({
                "name": "review_report.md readable",
                "passed": False,
                "detail": str(e)
            })
    
    checks.append({
        "name": "review_report.md exists",
        "passed": report_exists,
        "detail": f"Found at: {report_files[0]}" if report_files else "File not found. Agent must create review_report.md"
    })

    if not report_exists or not report_content:
        # Add remaining checks as failed
        for name in [
            "Report contains drawing number DWG-PUMP-4P-2024-001",
            "Report has 审核结论 section with checkbox",
            "Report has 问题汇总 table with correct columns",
            "q value correctly calculated and identified as problematic (q=18/(2×4×3)=0.75 OK, but LCM or ratio issue noted)",
            "气隙无公差 identified as 严重 severity",
            "轴承位(轴) H7 error identified (should be h6/k6/m6)",
            "键槽公差 H9 error identified (should be N9/P9)",
            "定子内圆跳动 0.05mm exceeds limit (≤0.03mm) identified",
            "轴承位圆柱度 IT7 error identified (should be IT6)",
            "粗糙度 Ra3.2 error identified for bearing position",
            "缺少GB/T 1804-m未注公差说明 identified",
            "材料牌号不明确 identified",
            "温升无具体数值 identified",
            "Report has 修改建议 section",
            "Report has 总体评价 section",
        ]:
            checks.append({"name": name, "passed": False, "detail": "report_report.md missing or unreadable"})
        
        score = sum(1 for c in checks if c["passed"]) / len(checks)
        return {"passed": False, "score": round(score, 3), "checks": checks}

    # =========================================================
    # CHECK 2: Drawing number present
    # =========================================================
    has_dwg_num = "DWG-PUMP-4P-2024-001" in report_content
    checks.append({
        "name": "Report contains drawing number DWG-PUMP-4P-2024-001",
        "passed": has_dwg_num,
        "detail": "Drawing number found" if has_dwg_num else "Drawing number not found in report"
    })

    # =========================================================
    # CHECK 3: 审核结论 section with checkbox
    # =========================================================
    has_conclusion = bool(re.search(r'审核结论', report_content))
    has_checkbox = bool(re.search(r'[□☐✓✗×]|通过|修改后通过|不通过', report_content))
    checks.append({
        "name": "Report has 审核结论 section with verdict",
        "passed": has_conclusion and has_checkbox,
        "detail": f"审核结论: {has_conclusion}, checkbox/verdict: {has_checkbox}"
    })

    # =========================================================
    # CHECK 4: 问题汇总 table with correct columns
    # =========================================================
    has_summary_table = bool(re.search(r'问题汇总', report_content))
    has_table_cols = (
        '位置' in report_content and
        '问题描述' in report_content and
        '严重程度' in report_content and
        '建议' in report_content
    )
    checks.append({
        "name": "Report has 问题汇总 table with correct columns",
        "passed": has_summary_table and has_table_cols,
        "detail": f"问题汇总: {has_summary_table}, table columns: {has_table_cols}"
    })

    # =========================================================
    # CHECK 5: q value calculation or pole-slot analysis
    # =========================================================
    # q = 18/(2*4*3) = 18/24 = 0.75
    # Agent should mention q value. The spec deliberately left it uncalculated.
    # q=0.75 is acceptable (>0.5), so this is an informational check
    # BUT the LCM(18,4)=36 — agent might note this. Main check: q was evaluated.
    has_q = bool(re.search(r'q\s*[=＝]\s*0\.75|每极每相槽数.*0\.75|0\.75.*每极|q值|极槽配合|LCM|lcm', report_content, re.IGNORECASE))
    checks.append({
        "name": "Pole-slot q value evaluated in report",
        "passed": has_q,
        "detail": "q=Q/(2pm)=18/(2×4×3)=0.75 should be computed and mentioned" if not has_q else "q value found"
    })

    # =========================================================
    # CHECK 6: 气隙无公差 identified as 严重
    # =========================================================
    gas_gap_issue = bool(re.search(r'气隙.{0,20}(无公差|未标注公差|缺少公差|公差未标)', report_content))
    gas_gap_severe = bool(re.search(r'(严重|严重程度).{0,60}气隙|气隙.{0,60}严重', report_content, re.DOTALL))
    checks.append({
        "name": "气隙无公差标注 identified as 严重 severity",
        "passed": gas_gap_issue and gas_gap_severe,
        "detail": f"Issue mentioned: {gas_gap_issue}, Severity=严重: {gas_gap_severe}"
    })

    # =========================================================
    # CHECK 7: Axis bearing H7 error (shaft should be h6/k6/m6, not H7)
    # =========================================================
    bearing_axis_error = bool(re.search(
        r'(轴承位.*轴.*H7|轴.*H7.*轴承|H7.*不应|轴公差.*H7|轴承位.*A端.*H7|A端.*H7.*错|H7.*应.*(h6|k6|m6))',
        report_content, re.IGNORECASE
    ))
    checks.append({
        "name": "轴承位(轴)公差H7错误 identified (should be h6/k6/m6)",
        "passed": bearing_axis_error,
        "detail": "Shaft at bearing A-end marked H7 should be h6/k6/m6 per SKILL.md spec"
    })

    # =========================================================
    # CHECK 8: 键槽公差 H9 error (should be N9/P9 per GB/T 1095)
    # =========================================================
    keyway_error = bool(re.search(
        r'(键槽.{0,30}H9|H9.{0,30}键槽|键槽.{0,30}(N9|P9)|键槽公差.*错|GB.?T\s*1095)',
        report_content, re.IGNORECASE
    ))
    checks.append({
        "name": "键槽公差H9错误 identified (should be N9/P9 per GB/T 1095)",
        "passed": keyway_error,
        "detail": "Keyway width tolerance H9 should be N9(hub) or P9(shaft) per GB/T 1095"
    })

    # =========================================================
    # CHECK 9: 定子内圆跳动 0.05mm exceeds ≤0.03mm
    # =========================================================
    stator_runout_error = bool(re.search(
        r'(定子内圆跳动.{0,40}0\.05|0\.05.{0,40}定子内圆|定子内圆.{0,40}超标|定子内圆.{0,40}0\.03)',
        report_content
    ))
    checks.append({
        "name": "定子内圆跳动0.05mm超标 identified (limit ≤0.03mm)",
        "passed": stator_runout_error,
        "detail": "Stator bore runout 0.05mm exceeds ≤0.03mm limit"
    })

    # =========================================================
    # CHECK 10: 轴承位圆柱度 IT7 error (should be IT6)
    # =========================================================
    cylindricity_error = bool(re.search(
        r'(圆柱度.{0,30}IT7|IT7.{0,30}圆柱度|IT7.*IT6|圆柱度.*错|轴承位.*IT7)',
        report_content
    ))
    checks.append({
        "name": "轴承位圆柱度IT7错误 identified (should be IT6)",
        "passed": cylindricity_error,
        "detail": "Bearing position cylindricity IT7 should be IT6"
    })

    # =========================================================
    # CHECK 11: 粗糙度 Ra3.2 error for bearing position
    # =========================================================
    roughness_error = bool(re.search(
        r'(轴承位.{0,30}Ra\s*3\.2|Ra\s*3\.2.{0,30}轴承|粗糙度.{0,40}轴承.{0,40}(错|超|应为|Ra\s*[01]\.))',
        report_content
    ))
    checks.append({
        "name": "轴承位粗糙度Ra3.2错误 identified (should be 0.8~1.6μm)",
        "passed": roughness_error,
        "detail": "Bearing position surface roughness Ra3.2 exceeds required Ra 0.8~1.6μm"
    })

    # =========================================================
    # CHECK 12: 缺少GB/T 1804-m未注公差说明
    # =========================================================
    untol_error = bool(re.search(
        r'(GB.?T\s*1804|未注公差|未注公差说明)',
        report_content
    ))
    checks.append({
        "name": "缺少GB/T 1804-m未注公差说明 identified",
        "passed": untol_error,
        "detail": "Drawing missing GB/T 1804-m general tolerance notation"
    })

    # =========================================================
    # CHECK 13: 材料牌号不明确 identified
    # =========================================================
    material_error = bool(re.search(
        r'(材料.{0,30}(牌号|型号).{0,30}(未|缺|不明)|硅钢片.{0,30}(牌号|型号).{0,30}(未|缺)|牌号未注)',
        report_content
    ))
    checks.append({
        "name": "材料牌号不明确 identified",
        "passed": material_error,
        "detail": "Silicon steel grade not specified in drawing"
    })

    # =========================================================
    # CHECK 14: 温升无具体数值 identified
    # =========================================================
    temp_rise_error = bool(re.search(
        r'(温升.{0,30}(未|无|缺).{0,30}(标注|数值|具体)|温升限值)',
        report_content
    ))
    checks.append({
        "name": "温升无具体数值 identified",
        "passed": temp_rise_error,
        "detail": "Temperature rise limit not specified with concrete value"
    })

    # =========================================================
    # CHECK 15: 修改建议 section present
    # =========================================================
    has_suggestions = bool(re.search(r'修改建议', report_content))
    checks.append({
        "name": "Report has 修改建议 section",
        "passed": has_suggestions,
        "detail": "修改建议 section found" if has_suggestions else "修改建议 section missing"
    })

    # =========================================================
    # CHECK 16: 总体评价 section present
    # =========================================================
    has_overall = bool(re.search(r'总体评价', report_content))
    checks.append({
        "name": "Report has 总体评价 section",
        "passed": has_overall,
        "detail": "总体评价 section found" if has_overall else "总体评价 section missing"
    })

    # =========================================================
    # Scoring
    # =========================================================
    total = len(checks)
    passed_count = sum(1 for c in checks if c["passed"])
    score = round(passed_count / total, 3)
    
    # Must pass critical checks to overall pass
    critical_checks = [
        "review_full.txt generated by checklist script",
        "review_report.md exists",
        "气隙无公差标注 identified as 严重 severity",
        "轴承位(轴)公差H7错误 identified (should be h6/k6/m6)",
        "键槽公差H9错误 identified (should be N9/P9 per GB/T 1095)",
        "定子内圆跳动0.05mm超标 identified (limit ≤0.03mm)",
        "Report has 问题汇总 table with correct columns",
    ]
    critical_passed = all(
        c["passed"] for c in checks if c["name"] in critical_checks
    )
    overall_passed = critical_passed and score >= 0.70

    return {
        "passed": overall_passed,
        "score": score,
        "checks": checks
    }


if __name__ == "__main__":
    workspace_path = sys.argv[1] if len(sys.argv) > 1 else "/workspace"
    result = evaluate(workspace_path)
    print(json.dumps(result, ensure_ascii=False, indent=2))