import sys
import json
import re
from pathlib import Path


def evaluate(workspace: str) -> dict:
    checks = []
    workspace_path = Path(workspace)

    # -----------------------------------------------------------------------
    # CHECK 1: report.md exists somewhere in the workspace
    # -----------------------------------------------------------------------
    report_files = list(workspace_path.rglob("report.md"))
    check1_passed = len(report_files) > 0
    checks.append({
        "name": "report.md file exists",
        "passed": check1_passed,
        "detail": f"Found {len(report_files)} report.md file(s): {[str(r) for r in report_files]}"
    })

    if not check1_passed:
        return {
            "passed": False,
            "score": 0.0,
            "checks": checks
        }

    # Use the first found report.md
    report_path = report_files[0]

    try:
        content = report_path.read_text(errors="replace")
    except Exception as e:
        checks.append({"name": "report.md readable", "passed": False, "detail": str(e)})
        return {"passed": False, "score": 0.0, "checks": checks}

    # -----------------------------------------------------------------------
    # CHECK 2: Report references the correct suspicious skill.md path
    # -----------------------------------------------------------------------
    correct_path_pattern = re.compile(
        r'vendor_submissions[/\\]zeta_systems[/\\]drafts[/\\]skill\.md', re.IGNORECASE
    )
    check2_passed = bool(correct_path_pattern.search(content))
    checks.append({
        "name": "Report references the correct audited file path",
        "passed": check2_passed,
        "detail": f"Expected path 'vendor_submissions/zeta_systems/drafts/skill.md' in report. Content snippet: {content[:300]}"
    })

    # -----------------------------------------------------------------------
    # CHECK 3: Risk Level is CRITICAL (as expected from the suspicious content)
    # -----------------------------------------------------------------------
    risk_pattern = re.compile(r'\*\*Risk Level:\*\*\s*(CRITICAL|HIGH|MEDIUM|LOW)', re.IGNORECASE)
    risk_match = risk_pattern.search(content)
    if risk_match:
        detected_risk = risk_match.group(1).upper()
        check3_passed = detected_risk in ("CRITICAL", "HIGH")
        checks.append({
            "name": "Risk level is CRITICAL or HIGH (matching suspicious content)",
            "passed": check3_passed,
            "detail": f"Detected risk level: {detected_risk}"
        })
    else:
        check3_passed = False
        checks.append({
            "name": "Risk level is CRITICAL or HIGH (matching suspicious content)",
            "passed": False,
            "detail": "No '**Risk Level:**' token found in report — likely not generated by audit.py"
        })

    # -----------------------------------------------------------------------
    # CHECK 4: Permission Manifest section present (proprietary audit.py output)
    # -----------------------------------------------------------------------
    manifest_pattern = re.compile(r'##\s+Permission Manifest', re.IGNORECASE)
    check4_passed = bool(manifest_pattern.search(content))
    checks.append({
        "name": "Permission Manifest section present in report",
        "passed": check4_passed,
        "detail": "Report must contain '## Permission Manifest' section — only audit.py emits this."
    })

    # -----------------------------------------------------------------------
    # CHECK 5: Network touches section lists at least one external domain
    # -----------------------------------------------------------------------
    network_section = re.compile(
        r'###\s+Network Touches(.*?)###\s+Filesystem', re.DOTALL | re.IGNORECASE
    )
    net_match = network_section.search(content)
    if net_match:
        net_block = net_match.group(1)
        # Should contain at least one domain from the suspicious skill
        has_domain = bool(re.search(r'zeta', net_block, re.IGNORECASE))
        check5_passed = has_domain
        checks.append({
            "name": "Network Touches includes Zeta external domains",
            "passed": check5_passed,
            "detail": f"Network touches block: {net_block.strip()[:300]}"
        })
    else:
        check5_passed = False
        checks.append({
            "name": "Network Touches includes Zeta external domains",
            "passed": False,
            "detail": "Could not find Network Touches block in report."
        })

    # -----------------------------------------------------------------------
    # CHECK 6: Filesystem touches section present and non-empty
    # -----------------------------------------------------------------------
    fs_section = re.compile(
        r'###\s+Filesystem Touches(.*?)(?:##|$)', re.DOTALL | re.IGNORECASE
    )
    fs_match = fs_section.search(content)
    if fs_match:
        fs_block = fs_match.group(1)
        # Should mention ~/.env or similar
        has_env = bool(re.search(r'\.env|HOME|tmp', fs_block, re.IGNORECASE))
        check6_passed = has_env
        checks.append({
            "name": "Filesystem Touches includes ~/.env or sensitive paths",
            "passed": check6_passed,
            "detail": f"Filesystem touches block: {fs_block.strip()[:300]}"
        })
    else:
        check6_passed = False
        checks.append({
            "name": "Filesystem Touches includes ~/.env or sensitive paths",
            "passed": False,
            "detail": "Could not find Filesystem Touches block in report."
        })

    # -----------------------------------------------------------------------
    # CHECK 7: Findings section has at least 2 individual findings
    # -----------------------------------------------------------------------
    findings_pattern = re.compile(r'##\s+Findings\s*\((\d+)\s+detected\)', re.IGNORECASE)
    findings_match = findings_pattern.search(content)
    if findings_match:
        num_findings = int(findings_match.group(1))
        check7_passed = num_findings >= 2
        checks.append({
            "name": "At least 2 findings detected and reported",
            "passed": check7_passed,
            "detail": f"Findings count in report: {num_findings}"
        })
    else:
        check7_passed = False
        checks.append({
            "name": "At least 2 findings detected and reported",
            "passed": False,
            "detail": "Could not find '## Findings (N detected)' header — output does not match audit.py format."
        })

    # -----------------------------------------------------------------------
    # CHECK 8: Summary section present with overall risk reiterated
    # -----------------------------------------------------------------------
    summary_pattern = re.compile(r'##\s+Summary', re.IGNORECASE)
    check8_passed = bool(summary_pattern.search(content))
    checks.append({
        "name": "Summary section present",
        "passed": check8_passed,
        "detail": "Report must contain '## Summary' section."
    })

    # -----------------------------------------------------------------------
    # Final scoring
    # -----------------------------------------------------------------------
    passed_checks = [c for c in checks if c["passed"]]
    total = len(checks)
    score = round(len(passed_checks) / total, 4)

    # Must pass critical checks to be overall pass
    critical = [check1_passed, check3_passed, check4_passed, check7_passed]
    overall_passed = all(critical) and score >= 0.75

    return {
        "passed": overall_passed,
        "score": score,
        "checks": checks
    }


if __name__ == "__main__":
    workspace_dir = sys.argv[1] if len(sys.argv) > 1 else "/workspace"
    result = evaluate(workspace_dir)
    print(json.dumps(result, indent=2))