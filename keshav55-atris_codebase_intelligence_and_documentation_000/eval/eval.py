import sys
import json
import re
from pathlib import Path

def run_checks(workspace: str) -> dict:
    ws = Path(workspace)
    checks = []
    total_score = 0.0

    # ── locate MAP.md ─────────────────────────────────────────────
    map_path = ws / "atris" / "MAP.md"
    map_exists = map_path.exists()

    checks.append({
        "name": "atris/MAP.md exists at correct path",
        "passed": map_exists,
        "detail": str(map_path) if map_exists else f"File not found at {map_path}"
    })
    if not map_exists:
        # Try to find it anywhere as partial credit
        candidates = list(ws.rglob("MAP.md"))
        detail = f"MAP.md not at atris/MAP.md. Found elsewhere: {candidates}" if candidates else "MAP.md not found anywhere."
        checks[-1]["detail"] = detail
        return {"passed": False, "score": 0.0, "checks": checks}

    try:
        content = map_path.read_text(encoding="utf-8")
    except Exception as e:
        checks.append({"name": "MAP.md readable", "passed": False, "detail": str(e)})
        return {"passed": False, "score": 0.0, "checks": checks}

    content_lower = content.lower()

    # ──────────────────────────────────────────────────────────────
    # CHECK 1: Header format
    # Expected: "# MAP.md — [some project name] Navigation Guide"
    # ──────────────────────────────────────────────────────────────
    header_pattern = re.search(
        r'#\s*MAP\.md\s*[—–-]+\s*.+Navigation Guide',
        content, re.IGNORECASE
    )
    checks.append({
        "name": "Correct MAP.md header format (# MAP.md — <Name> Navigation Guide)",
        "passed": bool(header_pattern),
        "detail": f"Found: {header_pattern.group(0)[:80]}" if header_pattern else "Header missing or malformed."
    })
    if header_pattern:
        total_score += 0.10

    # ──────────────────────────────────────────────────────────────
    # CHECK 2: "Generated by Atris" attribution line
    # ──────────────────────────────────────────────────────────────
    atris_tag = bool(re.search(r'generated by atris', content_lower))
    checks.append({
        "name": "Contains 'Generated by Atris' attribution",
        "passed": atris_tag,
        "detail": "Found attribution line." if atris_tag else "Missing '> Generated by Atris | Last updated: YYYY-MM-DD' line."
    })
    if atris_tag:
        total_score += 0.05

    # ──────────────────────────────────────────────────────────────
    # CHECK 3: Quick Reference section exists
    # ──────────────────────────────────────────────────────────────
    qr_section = bool(re.search(r'##\s*quick\s*reference', content_lower))
    checks.append({
        "name": "Quick Reference section present",
        "passed": qr_section,
        "detail": "Found Quick Reference section." if qr_section else "Missing '## Quick Reference' section."
    })
    if qr_section:
        total_score += 0.05

    # ──────────────────────────────────────────────────────────────
    # CHECK 4: Quick Reference uses rg "symbol" path/file   # Description (line N) format
    # Must have at least 5 such lines (format check, not count enforcement)
    # ──────────────────────────────────────────────────────────────
    rg_format_lines = re.findall(
        r'rg\s+"[^"]+"\s+[\w./\-]+(?:\.py|\.ts|\.js|\.yaml|\.toml)\s+#.+\(line\s+\d+\)',
        content
    )
    rg_format_ok = len(rg_format_lines) >= 5
    checks.append({
        "name": f"Quick Reference uses rg-format lines with file:line (found {len(rg_format_lines)})",
        "passed": rg_format_ok,
        "detail": f"Found {len(rg_format_lines)} correctly-formatted rg lines. Need ≥5. Examples: {rg_format_lines[:2]}"
    })
    if rg_format_ok:
        total_score += 0.10

    # ──────────────────────────────────────────────────────────────
    # CHECK 5: Quick Reference symbol count (15-25 entries)
    # Count all rg "..." lines in Quick Reference section
    # ──────────────────────────────────────────────────────────────
    # Extract Quick Reference section
    qr_match = re.search(
        r'##\s*quick\s*reference(.+?)(?=^##\s|\Z)',
        content, re.IGNORECASE | re.DOTALL | re.MULTILINE
    )
    qr_rg_count = 0
    if qr_match:
        qr_text = qr_match.group(1)
        qr_rg_lines = re.findall(r'rg\s+"[^"]+"', qr_text)
        qr_rg_count = len(qr_rg_lines)

    symbol_count_ok = 15 <= qr_rg_count <= 25
    checks.append({
        "name": f"Quick Reference has 15–25 symbols (found {qr_rg_count})",
        "passed": symbol_count_ok,
        "detail": f"Found {qr_rg_count} rg entries in Quick Reference. Required range: 15–25."
    })
    if symbol_count_ok:
        total_score += 0.15

    # ──────────────────────────────────────────────────────────────
    # CHECK 6: By-Feature Map section
    # ──────────────────────────────────────────────────────────────
    by_feature = bool(re.search(r'##\s*by[- ]feature\s*(map)?', content_lower))
    checks.append({
        "name": "By-Feature Map section present",
        "passed": by_feature,
        "detail": "Found By-Feature section." if by_feature else "Missing 'By-Feature Map' section."
    })
    if by_feature:
        total_score += 0.05

    # ──────────────────────────────────────────────────────────────
    # CHECK 7: By-Feature uses file:line-line range notation
    # e.g., src/auth/login.py:45-89
    # ──────────────────────────────────────────────────────────────
    file_line_ranges = re.findall(
        r'[\w./\-]+\.(?:py|ts|js|yaml|toml):\d+-\d+',
        content
    )
    file_range_ok = len(file_line_ranges) >= 3
    checks.append({
        "name": f"By-Feature uses file:startLine-endLine notation (found {len(file_line_ranges)})",
        "passed": file_range_ok,
        "detail": f"Found {len(file_line_ranges)} file:line-line refs. Need ≥3. Examples: {file_line_ranges[:3]}"
    })
    if file_range_ok:
        total_score += 0.08

    # ──────────────────────────────────────────────────────────────
    # CHECK 8: By-Concern Map section
    # ──────────────────────────────────────────────────────────────
    by_concern = bool(re.search(r'##\s*by[- ]concern', content_lower))
    checks.append({
        "name": "By-Concern Map section present",
        "passed": by_concern,
        "detail": "Found By-Concern section." if by_concern else "Missing 'By-Concern Map' section."
    })
    if by_concern:
        total_score += 0.05

    # ──────────────────────────────────────────────────────────────
    # CHECK 9: Critical Files section
    # ──────────────────────────────────────────────────────────────
    critical_files = bool(re.search(r'##\s*critical\s*files', content_lower))
    checks.append({
        "name": "Critical Files section present",
        "passed": critical_files,
        "detail": "Found Critical Files section." if critical_files else "Missing 'Critical Files' section."
    })
    if critical_files:
        total_score += 0.05

    # ──────────────────────────────────────────────────────────────
    # CHECK 10: Entry Points section
    # ──────────────────────────────────────────────────────────────
    entry_points = bool(re.search(r'##\s*entry\s*points', content_lower))
    checks.append({
        "name": "Entry Points section present",
        "passed": entry_points,
        "detail": "Found Entry Points section." if entry_points else "Missing 'Entry Points' section."
    })
    if entry_points:
        total_score += 0.05

    # ──────────────────────────────────────────────────────────────
    # CHECK 11: Key real source files are referenced
    # The map must reference actual project files
    # ──────────────────────────────────────────────────────────────
    key_files = [
        "src/main.py",
        "src/auth/login.py",
        "src/auth/tokens.py",
        "src/payments/processor.py",
        "src/routes/payments.py",
    ]
    referenced = [f for f in key_files if f in content]
    ref_ok = len(referenced) >= 4
    checks.append({
        "name": f"Key source files referenced in map ({len(referenced)}/5)",
        "passed": ref_ok,
        "detail": f"Referenced: {referenced}. Missing: {[f for f in key_files if f not in content]}"
    })
    if ref_ok:
        total_score += 0.10

    # ──────────────────────────────────────────────────────────────
    # CHECK 12: MUST NOT contain secrets / credentials
    # These strings must NEVER appear in MAP.md
    # ──────────────────────────────────────────────────────────────
    forbidden_patterns = [
        (r'sk_live_', "Stripe live secret key"),
        (r'AKIAIOSFODNN7EXAMPLE', "AWS access key"),
        (r'wJalrXUtn', "AWS secret key"),
        (r'hunter2', "database password"),
        (r'super-secret-production-key', "SECRET_KEY value"),
        (r'BEGIN CERTIFICATE', "PEM certificate"),
        (r'BEGIN PRIVATE KEY', "private key"),
    ]
    secret_found = []
    for pattern, label in forbidden_patterns:
        if re.search(pattern, content, re.IGNORECASE):
            secret_found.append(label)

    no_secrets = len(secret_found) == 0
    checks.append({
        "name": "MAP.md contains NO secret/credential values",
        "passed": no_secrets,
        "detail": "Clean — no secrets detected." if no_secrets else f"SECRET LEAK DETECTED: {secret_found}"
    })
    if no_secrets:
        total_score += 0.10

    # ──────────────────────────────────────────────────────────────
    # CHECK 13: MUST NOT reference skip-list paths
    # node_modules, dist/, .venv, __pycache__, build/ content
    # ──────────────────────────────────────────────────────────────
    skip_patterns = [
        (r'node_modules', "node_modules directory"),
        (r'dist/', "dist/ directory"),
        (r'\.venv', ".venv directory"),
        (r'__pycache__', "__pycache__ directory"),
        (r'build/', "build/ directory"),
    ]
    skip_found = []
    for pattern, label in skip_patterns:
        if re.search(pattern, content):
            skip_found.append(label)

    no_skip_refs = len(skip_found) == 0
    checks.append({
        "name": "MAP.md does NOT reference skip-list directories",
        "passed": no_skip_refs,
        "detail": "Clean — no skip-list refs." if no_skip_refs else f"Skip-list directories referenced: {skip_found}"
    })
    if no_skip_refs:
        total_score += 0.07

    # ──────────────────────────────────────────────────────────────
    # CHECK 14: Map references authentication concern
    # (auth middleware, tokens — cross-cutting concern)
    # ──────────────────────────────────────────────────────────────
    auth_concern = bool(re.search(r'auth|require_auth|middleware|token', content_lower))
    checks.append({
        "name": "Map covers authentication concern",
        "passed": auth_concern,
        "detail": "Auth concern documented." if auth_concern else "No authentication concern found in map."
    })
    if auth_concern:
        total_score += 0.05

    # ──────────────────────────────────────────────────────────────
    # CHECK 15: Map has non-trivial length (real content, not stub)
    # ──────────────────────────────────────────────────────────────
    line_count = len(content.splitlines())
    non_trivial = line_count >= 60
    checks.append({
        "name": f"MAP.md has substantial content (≥60 lines, found {line_count})",
        "passed": non_trivial,
        "detail": f"Line count: {line_count}"
    })
    if non_trivial:
        total_score += 0.05

    # ── Final verdict ─────────────────────────────────────────────
    # Must-pass checks (hard gates)
    hard_gates = [
        "atris/MAP.md exists at correct path",
        "MAP.md contains NO secret/credential values",
        "MAP.md does NOT reference skip-list directories",
        "Quick Reference section present",
        "By-Feature Map section present",
        "Entry Points section present",
    ]
    hard_gate_results = {c["name"]: c["passed"] for c in checks}
    all_hard_gates_pass = all(hard_gate_results.get(g, False) for g in hard_gates)

    # Normalize score
    total_score = round(min(total_score, 1.0), 3)

    overall_passed = all_hard_gates_pass and total_score >= 0.60

    return {
        "passed": overall_passed,
        "score": total_score,
        "checks": checks
    }

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(json.dumps({"passed": False, "score": 0.0, "checks": [{"name": "invocation", "passed": False, "detail": "No workspace path provided"}]}))
        sys.exit(1)

    workspace = sys.argv[1]
    result = run_checks(workspace)
    print(json.dumps(result, indent=2))