import sys
import json
import os
from pathlib import Path

def check(name, passed, detail=""):
    return {"name": name, "passed": passed, "detail": detail}

def run_eval(workspace_str):
    workspace = Path(workspace_str)
    checks = []
    total_score = 0.0
    weights = []

    # ── CHECK 1: garden init was run (garden.yaml exists and is valid) ──
    try:
        garden_yaml = workspace / "garden.yaml"
        if not garden_yaml.exists():
            # also search recursively in case agent put it somewhere else
            candidates = list(workspace.rglob("garden.yaml"))
            garden_yaml = candidates[0] if candidates else None

        if garden_yaml and garden_yaml.exists():
            content = garden_yaml.read_text()
            # Must not be the broken stub
            is_real = "wrong_path" not in content and len(content) > 20
            checks.append(check("garden.yaml created by init", is_real,
                                 f"Found at {garden_yaml}, valid={is_real}, snippet={content[:120]}"))
            weights.append((is_real, 0.15))
        else:
            checks.append(check("garden.yaml created by init", False, "garden.yaml not found anywhere in workspace"))
            weights.append((False, 0.15))
    except Exception as e:
        checks.append(check("garden.yaml created by init", False, str(e)))
        weights.append((False, 0.15))

    # ── CHECK 2: memory/entities/ directory was created ──
    try:
        entities_dir = workspace / "memory" / "entities"
        exists = entities_dir.exists() and entities_dir.is_dir()
        entity_files = list(entities_dir.rglob("*.md")) if exists else []
        checks.append(check("memory/entities/ directory exists", exists,
                             f"Exists={exists}, entity pages found={len(entity_files)}"))
        weights.append((exists, 0.10))
    except Exception as e:
        checks.append(check("memory/entities/ directory exists", False, str(e)))
        weights.append((False, 0.10))

    # ── CHECK 3: graph.jsonl was created ──
    try:
        graph_file = workspace / "graph.jsonl"
        if not graph_file.exists():
            candidates = list(workspace.rglob("graph.jsonl"))
            graph_file = candidates[0] if candidates else None

        if graph_file and graph_file.exists():
            lines = [l.strip() for l in graph_file.read_text().splitlines() if l.strip()]
            has_content = len(lines) > 0
            # Validate at least one line is parseable JSON
            valid_json = False
            for line in lines[:5]:
                try:
                    json.loads(line)
                    valid_json = True
                    break
                except Exception:
                    pass
            passed = has_content and valid_json
            checks.append(check("graph.jsonl created and populated", passed,
                                 f"Lines={len(lines)}, valid_json_line={valid_json}"))
            weights.append((passed, 0.20))
        else:
            checks.append(check("graph.jsonl created and populated", False, "graph.jsonl not found"))
            weights.append((False, 0.20))
    except Exception as e:
        checks.append(check("graph.jsonl created and populated", False, str(e)))
        weights.append((False, 0.20))

    # ── CHECK 4: extract produced entity wiki pages from conversations ──
    try:
        entities_dir = workspace / "memory" / "entities"
        entity_files = list(entities_dir.rglob("*.md")) if entities_dir.exists() else []
        has_entities = len(entity_files) >= 2  # At minimum a few entities extracted
        
        # Check content of at least one entity page for wikilink-style or fact content
        has_substantive = False
        sample_content = ""
        for ef in entity_files[:5]:
            try:
                c = ef.read_text()
                sample_content = c[:200]
                # Should have some content beyond just a title
                if len(c) > 30:
                    has_substantive = True
                    break
            except Exception:
                pass

        passed = has_entities and has_substantive
        checks.append(check("extract produced entity wiki pages", passed,
                             f"Entity pages={len(entity_files)}, substantive={has_substantive}, sample='{sample_content[:100]}'"))
        weights.append((passed, 0.20))
    except Exception as e:
        checks.append(check("extract produced entity wiki pages", False, str(e)))
        weights.append((False, 0.20))

    # ── CHECK 5: RECALL-CONTEXT.md was generated by inject ──
    try:
        recall_file = workspace / "RECALL-CONTEXT.md"
        if not recall_file.exists():
            candidates = list(workspace.rglob("RECALL-CONTEXT.md"))
            recall_file = candidates[0] if candidates else None

        if recall_file and recall_file.exists():
            content = recall_file.read_text()
            # Must be non-trivial — not just an empty file
            has_content = len(content.strip()) > 50
            # Should reference at least some extracted knowledge (entities/compounds mentioned in convos)
            knowledge_terms = ["veratromine", "neuroflux", "synaptinol", "kx-7", "kinase", 
                               "ryo", "kirchner", "osei", "cpd-", "ic50", "compound", "inhibit"]
            found_terms = [t for t in knowledge_terms if t.lower() in content.lower()]
            has_knowledge = len(found_terms) >= 2
            passed = has_content and has_knowledge
            checks.append(check("RECALL-CONTEXT.md generated with knowledge content", passed,
                                 f"Length={len(content)}, terms_found={found_terms[:5]}, snippet='{content[:150]}'"))
            weights.append((passed, 0.25))
        else:
            checks.append(check("RECALL-CONTEXT.md generated with knowledge content", False,
                                 "RECALL-CONTEXT.md not found anywhere in workspace"))
            weights.append((False, 0.25))
    except Exception as e:
        checks.append(check("RECALL-CONTEXT.md generated with knowledge content", False, str(e)))
        weights.append((False, 0.25))

    # ── CHECK 6: surprise/consolidate pipeline ran (evidence in memory structure) ──
    try:
        # After surprise + consolidate, there should be either a surprise score file,
        # updated entity pages, or some artifact. We check for any of these.
        # garden surprise can update graph.jsonl entries with surprise scores.
        # We look for any file modified after init that isn't the conversations themselves.
        memory_dir = workspace / "memory"
        
        # Check graph.jsonl for surprise score fields OR check for any memory subdir files
        graph_file = workspace / "graph.jsonl"
        if not graph_file.exists():
            candidates = list(workspace.rglob("graph.jsonl"))
            graph_file = candidates[0] if candidates else None

        has_surprise_evidence = False
        detail_str = "No surprise evidence found"

        if graph_file and graph_file.exists():
            graph_content = graph_file.read_text()
            # Surprise scoring adds fields like "surprise", "score", or timestamps
            if any(kw in graph_content.lower() for kw in ["surprise", "score", "confidence", "conflict", "decay"]):
                has_surprise_evidence = True
                detail_str = "surprise/confidence fields found in graph.jsonl"

        # Alternatively: check if memory dir has additional subdirs (consolidate may create indices)
        if not has_surprise_evidence and memory_dir.exists():
            subdirs = [d for d in memory_dir.iterdir() if d.is_dir()]
            if len(subdirs) >= 1:
                has_surprise_evidence = True
                detail_str = f"memory subdirs exist: {[d.name for d in subdirs]}"

        # Fallback: if entity files exist with more than basic content, pipeline ran
        if not has_surprise_evidence:
            entity_files = list((workspace / "memory" / "entities").rglob("*.md")) \
                           if (workspace / "memory" / "entities").exists() else []
            if len(entity_files) >= 3:
                has_surprise_evidence = True
                detail_str = f"Entity pipeline produced {len(entity_files)} pages (consolidate evidence)"

        checks.append(check("surprise+consolidate pipeline evidence", has_surprise_evidence, detail_str))
        weights.append((has_surprise_evidence, 0.10))
    except Exception as e:
        checks.append(check("surprise+consolidate pipeline evidence", False, str(e)))
        weights.append((False, 0.10))

    # ── Compute final score ──
    score = sum(w for passed, w in weights if passed)
    all_passed = all(p for p, _ in weights)

    return {
        "passed": all_passed,
        "score": round(score, 3),
        "checks": checks
    }

if __name__ == "__main__":
    workspace_dir = sys.argv[1] if len(sys.argv) > 1 else "/workspace"
    result = run_eval(workspace_dir)
    print(json.dumps(result, indent=2))