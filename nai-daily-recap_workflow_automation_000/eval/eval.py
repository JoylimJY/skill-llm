import sys
import json
import re
from pathlib import Path

def evaluate(workspace: str):
    ws = Path(workspace)
    TEST_DATE = "2025-06-10"
    vault_entry_path = ws / f"vault/daily-recap/{TEST_DATE}.md"
    memory_path = ws / f"memory/{TEST_DATE}.md"

    checks = []
    total_score = 0.0
    weights = {}

    def check(name, weight, passed, detail):
        checks.append({"name": name, "passed": passed, "detail": detail})
        nonlocal total_score
        if passed:
            total_score += weight

    # ── Load vault entry ──────────────────────────────────────────────────────
    try:
        vault_content = vault_entry_path.read_text(encoding="utf-8")
    except Exception as e:
        checks.append({"name": "vault_entry_readable", "passed": False, "detail": str(e)})
        return {"passed": False, "score": 0.0, "checks": checks}

    check("vault_entry_readable", 0.0, True, f"File exists at {vault_entry_path}")

    # ── Check 1: File was NOT overwritten — original content still present ────
    original_marker = "## Requests & Tasks\n- Researched open-source vector databases for RAG pipeline comparison."
    original_present = original_marker in vault_content
    check(
        "original_content_preserved",
        0.15,
        original_present,
        "Original partial recap content must still be present (no overwrite allowed)." if not original_present
        else "Original content intact."
    )

    # ── Check 2: Addendum section appended ───────────────────────────────────
    has_addendum = "## Addendum" in vault_content
    check(
        "addendum_section_present",
        0.20,
        has_addendum,
        "An '## Addendum' section must be appended since the file already existed." if not has_addendum
        else "## Addendum found."
    )

    # ── Check 3: Addendum contains afternoon/evening activity ─────────────────
    # Must mention the Athena update, Qdrant decision, or backup research
    addendum_mentions_afternoon = False
    if has_addendum:
        addendum_idx = vault_content.index("## Addendum")
        addendum_text = vault_content[addendum_idx:]
        afternoon_keywords = [
            "athena", "snapshot", "backup", "qdrant", "decision", "production",
            "fine-tun", "timeout", "docker", "16:10", "17:30", "18:00", "bench"
        ]
        addendum_mentions_afternoon = any(kw.lower() in addendum_text.lower() for kw in afternoon_keywords)
    check(
        "addendum_covers_afternoon_activity",
        0.20,
        addendum_mentions_afternoon,
        "Addendum must include afternoon/evening activities from memory log." if not addendum_mentions_afternoon
        else "Addendum references afternoon activity."
    )

    # ── Check 4: Atlas footer present ─────────────────────────────────────────
    atlas_footer = "*Auto-generated by Atlas at end of day.*"
    has_atlas_footer = atlas_footer in vault_content
    check(
        "atlas_footer_present",
        0.10,
        has_atlas_footer,
        f"Footer '{atlas_footer}' must appear in the file." if not has_atlas_footer
        else "Atlas footer found."
    )

    # ── Check 5: YAML frontmatter has required fields ─────────────────────────
    # Parse the original frontmatter (first YAML block)
    fm_match = re.match(r"^---\n(.*?)\n---", vault_content, re.DOTALL)
    fm_fields_ok = False
    fm_detail = "No valid YAML frontmatter found."
    if fm_match:
        fm_text = fm_match.group(1)
        has_type = "type: daily-recap" in fm_text
        has_source = "source: agent" in fm_text
        has_date = f"date: {TEST_DATE}" in fm_text
        fm_fields_ok = has_type and has_source and has_date
        fm_detail = (
            f"type={'OK' if has_type else 'MISSING'}, "
            f"source={'OK' if has_source else 'MISSING'}, "
            f"date={'OK' if has_date else 'MISSING'}"
        )
    check(
        "frontmatter_required_fields",
        0.10,
        fm_fields_ok,
        fm_detail
    )

    # ── Check 6: Tags field present and non-trivial ───────────────────────────
    tags_ok = False
    tags_detail = "No tags field found."
    if fm_match:
        fm_text = fm_match.group(1)
        tags_match = re.search(r"tags:\s*\[(.+?)\]", fm_text)
        if tags_match:
            tags_str = tags_match.group(1)
            tags = [t.strip() for t in tags_str.split(",")]
            has_daily_recap_tag = "daily-recap" in tags
            has_topic_tags = len(tags) >= 2  # at least one auto-detected topic
            tags_ok = has_daily_recap_tag and has_topic_tags
            tags_detail = f"Tags found: {tags}. daily-recap tag: {has_daily_recap_tag}, topic tags: {has_topic_tags}"
        else:
            tags_detail = "tags field malformed or missing."
    check(
        "tags_present_and_nontrivial",
        0.05,
        tags_ok,
        tags_detail
    )

    # ── Check 7: Memory log updated with recap completion note ────────────────
    try:
        memory_content = memory_path.read_text(encoding="utf-8")
        recap_keywords = ["recap", "written", "completed", "addendum", "daily recap"]
        memory_updated = any(kw.lower() in memory_content.lower() for kw in recap_keywords)
        # Must appear AFTER the original content
        original_memory_end = "Logged in errors."
        if original_memory_end in memory_content:
            after_original = memory_content[memory_content.index(original_memory_end):]
            memory_updated = any(kw.lower() in after_original.lower() for kw in recap_keywords)
        check(
            "memory_log_updated",
            0.15,
            memory_updated,
            "memory/2025-06-10.md must be appended with a note that the recap was written." if not memory_updated
            else "Memory log contains recap completion note."
        )
    except Exception as e:
        check("memory_log_updated", 0.15, False, f"Could not read memory log: {e}")

    # ── Check 8: Requests section faithfully captures Ryan's actual words ─────
    # "can you research the best open-source vector databases" should be paraphrasable
    # but the gist must be intact — check for key concepts
    requests_faithful = False
    requests_detail = "No Requests section or gist not captured faithfully."
    req_section_match = re.search(r"## Requests.*?(?=##|\Z)", vault_content, re.DOTALL)
    if req_section_match:
        req_text = req_section_match.group(0)
        req_keywords = ["vector database", "vector db", "rag", "benchmark", "athena", "open-source", "script"]
        matched = [kw for kw in req_keywords if kw.lower() in req_text.lower()]
        requests_faithful = len(matched) >= 2
        requests_detail = f"Matched keywords: {matched}"
    check(
        "requests_section_gist_faithful",
        0.05,
        requests_faithful,
        requests_detail
    )

    # ── Final aggregation ─────────────────────────────────────────────────────
    # Core mandatory checks: original preserved + addendum present + memory updated
    mandatory_passed = (
        original_present and
        has_addendum and
        addendum_mentions_afternoon and
        memory_updated
    )

    overall_passed = mandatory_passed and total_score >= 0.55

    return {
        "passed": overall_passed,
        "score": round(total_score, 3),
        "checks": checks
    }


if __name__ == "__main__":
    workspace = sys.argv[1] if len(sys.argv) > 1 else "/workspace"
    result = evaluate(workspace)
    print(json.dumps(result, indent=2))