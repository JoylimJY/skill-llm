# Create bundle-artifact.sh
bundle_script = r"""#!/bin/bash
set -e

echo "Bundling React app to single HTML artifact..."

if [ ! -f "package.json" ]; then
  echo "Error: No package.json found."
  exit 1
fi

if [ ! -f "index.html" ]; then
  echo "Error: No index.html found."
  exit 1
fi

pnpm add -D parcel @parcel/config-default parcel-resolver-tspaths html-inline

if [ ! -f ".parcelrc" ]; then
  cat > .parcelrc << 'EOF'
{
  "extends": "@parcel/config-default",
  "resolvers": ["parcel-resolver-tspaths", "..."]
}
EOF
fi

rm -rf dist bundle.html

pnpm exec parcel build index.html --dist-dir dist --no-source-maps

pnpm exec html-inline dist/index.html > bundle.html

FILE_SIZE=$(du -h bundle.html | cut -f1)
echo "Bundle complete! Output: bundle.html ($FILE_SIZE)"
"""

with open('scripts/bundle-artifact.sh', 'w') as f:
    f.write(bundle_script)
os.chmod('scripts/bundle-artifact.sh', 0o755)

# Create a minimal shadcn-components.tar.gz with just the button component and utils
components_files = {
    'components/ui/button.tsx': '''import * as React from "react"
import { Slot } from "@radix-ui/react-slot"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "@/lib/utils"

const buttonVariants = cva(
  "inline-flex items-center justify-center gap-2 whitespace-nowrap rounded-md text-sm font-medium transition-colors focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-ring disabled:pointer-events-none disabled:opacity-50",
  {
    variants: {
      variant: {
        default: "bg-primary text-primary-foreground shadow hover:bg-primary/90",
        destructive: "bg-destructive text-destructive-foreground shadow-sm hover:bg-destructive/90",
        outline: "border border-input bg-background shadow-sm hover:bg-accent hover:text-accent-foreground",
        secondary: "bg-secondary text-secondary-foreground shadow-sm hover:bg-secondary/80",
        ghost: "hover:bg-accent hover:text-accent-foreground",
        link: "text-primary underline-offset-4 hover:underline",
      },
      size: {
        default: "h-9 px-4 py-2",
        sm: "h-8 rounded-md px-3 text-xs",
        lg: "h-10 rounded-md px-8",
        icon: "h-9 w-9",
      },
    },
    defaultVariants: {
      variant: "default",
      size: "default",
    },
  }
)

export interface ButtonProps
  extends React.ButtonHTMLAttributes<HTMLButtonElement>,
    VariantProps<typeof buttonVariants> {
  asChild?: boolean
}

const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(
  ({ className, variant, size, asChild = false, ...props }, ref) => {
    const Comp = asChild ? Slot : "button"
    return (
      <Comp
        className={cn(buttonVariants({ variant, size, className }))}
        ref={ref}
        {...props}
      />
    )
  }
)
Button.displayName = "Button"

export { Button, buttonVariants }
''',
    'lib/utils.ts': '''import { clsx, type ClassValue } from "clsx"
import { twMerge } from "tailwind-merge"

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs))
}
'''
}

# Create tar.gz
buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode='w:gz') as tar:
    for filename, content in components_files.items():
        content_bytes = content.encode('utf-8')
        info = tarfile.TarInfo(name=filename)
        info.size = len(content_bytes)
        tar.addfile(info, io.BytesIO(content_bytes))

with open('scripts/shadcn-components.tar.gz', 'wb') as f:
    f.write(buf.getvalue())

print('Input files created successfully.')
