import sys
import json
import re
from pathlib import Path

def check(name, passed, detail):
    return {"name": name, "passed": passed, "detail": detail}

def run_eval(workspace_str):
    workspace = Path(workspace_str)
    checks = []

    contract_name = "webapp-dev-agreement"
    draft_root = workspace / "contracts" / "drafting" / contract_name

    # ── CHECK 1: Draft directory exists ──
    checks.append(check(
        "draft_directory_exists",
        draft_root.is_dir(),
        f"Expected directory at {draft_root}"
    ))

    # ── CHECK 2: current.md exists ──
    current_path = draft_root / "current.md"
    current_exists = current_path.exists()
    checks.append(check(
        "current_md_exists",
        current_exists,
        f"current.md at {current_path}"
    ))

    current_text = ""
    if current_exists:
        try:
            current_text = current_path.read_text(encoding="utf-8", errors="replace")
        except Exception as e:
            checks.append(check("current_md_readable", False, str(e)))
            current_text = ""

    # ── CHECK 3: Mandatory AI disclaimer in current.md ──
    disclaimer_phrases = [
        "generated by AI",
        "does NOT constitute legal advice",
        "licensed attorney"
    ]
    disclaimer_found = all(phrase.lower() in current_text.lower() for phrase in disclaimer_phrases)
    checks.append(check(
        "mandatory_ai_disclaimer_present",
        disclaimer_found,
        "current.md must contain: 'generated by AI', 'does NOT constitute legal advice', 'licensed attorney'"
    ))

    # ── CHECK 4: versions/v001.md exists ──
    versions_dir = draft_root / "versions"
    v001_path = versions_dir / "v001.md"
    v001_exists = v001_path.exists()
    checks.append(check(
        "versions_v001_exists",
        v001_exists,
        f"versions/v001.md must exist at {v001_path} (version control rule: copy to versions, never edit in place)"
    ))

    # ── CHECK 5: v001.md has substantive content (not empty/stub) ──
    v001_text = ""
    if v001_exists:
        try:
            v001_text = v001_path.read_text(encoding="utf-8", errors="replace")
        except Exception as e:
            v001_text = ""
    v001_substantial = len(v001_text.strip()) > 200
    checks.append(check(
        "v001_has_substantive_content",
        v001_substantial,
        f"v001.md has {len(v001_text.strip())} chars; expected > 200"
    ))

    # ── CHECK 6: current.md and v001.md content match (version control parity) ──
    if current_text and v001_text:
        # They should be essentially the same draft (current is the latest = v001 at this stage)
        # We allow minor whitespace differences but core content should overlap significantly
        current_stripped = re.sub(r'\s+', ' ', current_text.strip().lower())
        v001_stripped = re.sub(r'\s+', ' ', v001_text.strip().lower())
        # Check that a large fraction of v001 content appears in current
        # Use a simple word overlap metric
        current_words = set(current_stripped.split())
        v001_words = set(v001_stripped.split())
        if v001_words:
            overlap = len(current_words & v001_words) / len(v001_words)
        else:
            overlap = 0
        version_parity = overlap > 0.6
        checks.append(check(
            "current_md_matches_v001",
            version_parity,
            f"current.md and v001.md should have overlapping content (word overlap: {overlap:.2f})"
        ))
    else:
        checks.append(check(
            "current_md_matches_v001",
            False,
            "Cannot compare: one or both files missing/empty"
        ))

    # ── CHECK 7: intake.md exists and has discovery answers ──
    intake_path = draft_root / "intake.md"
    intake_exists = intake_path.exists()
    intake_text = ""
    if intake_exists:
        try:
            intake_text = intake_path.read_text(encoding="utf-8", errors="replace")
        except Exception:
            pass
    intake_has_answers = intake_exists and len(intake_text.strip()) > 100
    # Must reference key intake topics for a services agreement
    intake_keywords = ["service", "client", "payment", "deliverable"]
    intake_keywords_found = sum(1 for kw in intake_keywords if kw.lower() in intake_text.lower())
    checks.append(check(
        "intake_md_has_discovery_answers",
        intake_has_answers and intake_keywords_found >= 3,
        f"intake.md must contain discovery answers (found {intake_keywords_found}/4 keywords, length={len(intake_text.strip())})"
    ))

    # ── CHECK 8: parties.md exists and lists both parties ──
    parties_path = draft_root / "parties.md"
    parties_exists = parties_path.exists()
    parties_text = ""
    if parties_exists:
        try:
            parties_text = parties_path.read_text(encoding="utf-8", errors="replace")
        except Exception:
            pass
    # Must mention at least two distinct parties with some detail
    # Look for indicators: "client", "provider", "party" or proper names
    party_indicators = ["client", "provider", "developer", "freelance", "party"]
    party_count = sum(1 for ind in party_indicators if ind.lower() in parties_text.lower())
    parties_valid = parties_exists and len(parties_text.strip()) > 50 and party_count >= 2
    checks.append(check(
        "parties_md_lists_parties",
        parties_valid,
        f"parties.md must list both parties with interests (indicators found: {party_count}/5, length={len(parties_text.strip())})"
    ))

    # ── CHECK 9: notes.md exists and has risk/negotiation content ──
    notes_path = draft_root / "notes.md"
    notes_exists = notes_path.exists()
    notes_text = ""
    if notes_exists:
        try:
            notes_text = notes_path.read_text(encoding="utf-8", errors="replace")
        except Exception:
            pass
    # Must have more content than the stub (original stub was ~180 chars)
    # And must contain risk or negotiation analysis
    risk_keywords = ["risk", "scope", "ip", "liability", "payment", "ownership", "alternative", "concern", "mitigation"]
    risk_kw_found = sum(1 for kw in risk_keywords if kw.lower() in notes_text.lower())
    notes_valid = notes_exists and len(notes_text.strip()) > 150 and risk_kw_found >= 2
    checks.append(check(
        "notes_md_has_risk_analysis",
        notes_valid,
        f"notes.md must have risk/negotiation content (risk keywords: {risk_kw_found}/9, length={len(notes_text.strip())})"
    ))

    # ── CHECK 10: current.md has mandatory contract sections ──
    required_sections = [
        r"scope.{0,20}work",
        r"compensation|payment",
        r"intellectual.{0,10}property|ip\b",
        r"termination",
        r"governing.{0,10}law|jurisdiction",
        r"limitation.{0,10}liabilit|liability"
    ]
    sections_found = []
    for pattern in required_sections:
        if re.search(pattern, current_text, re.IGNORECASE):
            sections_found.append(pattern)
    sections_pass = len(sections_found) >= 4
    checks.append(check(
        "current_md_has_required_sections",
        sections_pass,
        f"current.md must include key sections (found {len(sections_found)}/6 patterns: {sections_found})"
    ))

    # ── CHECK 11: disclaimer also present in v001.md ──
    v001_disclaimer = all(phrase.lower() in v001_text.lower() for phrase in disclaimer_phrases)
    checks.append(check(
        "v001_has_ai_disclaimer",
        v001_disclaimer,
        "v001.md (versioned copy) must also contain the mandatory AI disclaimer"
    ))

    # ── CHECK 12: Agent did NOT pollute unrelated contract directories ──
    # The old NDA draft should not have been modified (its notes.md should remain as stub)
    old_nda_notes = workspace / "contracts" / "drafting" / "nda-vendor-2023" / "notes.md"
    try:
        old_notes_text = old_nda_notes.read_text(encoding="utf-8", errors="replace")
        # Should still contain the original content about vendor withdrawing
        unmodified = "vendor withdrew" in old_notes_text.lower() or "withdrew" in old_notes_text.lower()
        checks.append(check(
            "unrelated_draft_not_modified",
            unmodified,
            "The existing nda-vendor-2023 draft should not have been altered"
        ))
    except Exception as e:
        checks.append(check("unrelated_draft_not_modified", False, f"Could not read old NDA notes: {e}"))

    # ── SCORING ──
    total = len(checks)
    passed_count = sum(1 for c in checks if c["passed"])
    score = round(passed_count / total, 4)
    overall_passed = passed_count >= 9  # must pass at least 9/12 checks

    return {
        "passed": overall_passed,
        "score": score,
        "checks": checks
    }

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(json.dumps({"passed": False, "score": 0.0, "checks": [
            {"name": "argument_error", "passed": False, "detail": "No workspace path provided"}
        ]}))
        sys.exit(1)

    result = run_eval(sys.argv[1])
    print(json.dumps(result, indent=2))