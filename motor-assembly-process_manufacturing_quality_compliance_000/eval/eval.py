#!/usr/bin/env python3
"""
Evaluation script for the motor assembly audit task.
Checks:
1. checklist_full.txt was generated by running assembly_checklist.py --stage full --output
2. The checklist contains expected stage markers
3. audit_report.json exists and has correct GJB traceability data
   - Correct form numbers AND correct retention years (the key proprietary trap)
4. Electrical test thresholds are correct in the JSON
5. Bearing heating max temperature is correctly stated (≤120°C, not 150°C from distractor)
"""

import sys
import json
import re
from pathlib import Path

def run_checks(workspace: str):
    ws = Path(workspace)
    checks = []
    total_score = 0.0

    # ---------------------------------------------------------------
    # CHECK 1: checklist_full.txt exists and has correct content
    # ---------------------------------------------------------------
    checklist_files = list(ws.rglob("checklist_full.txt"))
    if not checklist_files:
        checks.append({
            "name": "checklist_full.txt exists",
            "passed": False,
            "detail": "File checklist_full.txt not found anywhere in workspace."
        })
    else:
        cf = checklist_files[0]
        try:
            content = cf.read_text(encoding="utf-8")
            # Should contain rotor, stator, bearing, and electrical items
            has_rotor = "ROTOR" in content.upper() or "转子" in content
            has_stator = "STATOR" in content.upper() or "定子" in content
            has_bearing = "BEARING" in content.upper() or "轴承" in content
            has_elec = "ELEC" in content.upper() or "绝缘" in content or "耐压" in content
            has_end = "END OF CHECKLIST" in content or "END" in content.upper()

            all_sections = has_rotor and has_stator and has_bearing and has_elec
            checks.append({
                "name": "checklist_full.txt exists",
                "passed": True,
                "detail": f"Found at {cf}"
            })
            checks.append({
                "name": "checklist_full.txt contains all 4 assembly stages (rotor/stator/bearing/electrical)",
                "passed": all_sections,
                "detail": f"rotor={has_rotor}, stator={has_stator}, bearing={has_bearing}, elec={has_elec}, end={has_end}"
            })
            if all_sections:
                total_score += 0.20
        except Exception as e:
            checks.append({
                "name": "checklist_full.txt readable",
                "passed": False,
                "detail": f"Error reading file: {e}"
            })

    # ---------------------------------------------------------------
    # CHECK 2: audit_report.json exists
    # ---------------------------------------------------------------
    report_files = list(ws.rglob("audit_report.json"))
    if not report_files:
        checks.append({
            "name": "audit_report.json exists",
            "passed": False,
            "detail": "File audit_report.json not found anywhere in workspace."
        })
        # Cannot do further checks
        result = {
            "passed": False,
            "score": total_score / 1.0,
            "checks": checks
        }
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return

    rf = report_files[0]
    checks.append({
        "name": "audit_report.json exists",
        "passed": True,
        "detail": f"Found at {rf}"
    })

    try:
        report = json.loads(rf.read_text(encoding="utf-8"))
    except Exception as e:
        checks.append({
            "name": "audit_report.json is valid JSON",
            "passed": False,
            "detail": f"JSON parse error: {e}"
        })
        result = {
            "passed": False,
            "score": total_score,
            "checks": checks
        }
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return

    checks.append({
        "name": "audit_report.json is valid JSON",
        "passed": True,
        "detail": "Parsed successfully."
    })

    # ---------------------------------------------------------------
    # CHECK 3: GJB Quality Records - Form Numbers and Retention Periods
    # The KEY proprietary trap: mixed retention years (5 vs 10)
    # FRM-ASM-001: 5年
    # FRM-ASM-002: 10年
    # FRM-ASM-003: 10年
    # FRM-EM-001:  10年
    # FRM-ASM-004: 5年
    # FRM-ASM-005: 10年
    # ---------------------------------------------------------------
    EXPECTED_RECORDS = {
        "FRM-ASM-001": 5,
        "FRM-ASM-002": 10,
        "FRM-ASM-003": 10,
        "FRM-EM-001": 10,
        "FRM-ASM-004": 5,
        "FRM-ASM-005": 10,
    }

    # Flatten the report into a string for searching
    report_str = json.dumps(report, ensure_ascii=False)

    # Find all form numbers present
    found_forms = {}
    for form_id in EXPECTED_RECORDS:
        if form_id in report_str:
            found_forms[form_id] = True

    form_coverage = len(found_forms) / len(EXPECTED_RECORDS)
    checks.append({
        "name": "audit_report.json references all 6 GJB form numbers",
        "passed": form_coverage == 1.0,
        "detail": f"Found {len(found_forms)}/6 forms: {list(found_forms.keys())}"
    })
    if form_coverage == 1.0:
        total_score += 0.20

    # Check retention periods - must distinguish 5-year vs 10-year records
    # Search the JSON structure for form+retention pairs
    def extract_retention_for_form(report_obj, form_id):
        """Recursively search report for retention period associated with form_id."""
        report_text = json.dumps(report_obj, ensure_ascii=False)
        # Look for patterns: "FRM-ASM-001" near "5" (years)
        # We look for the form_id and then any number 5 or 10 nearby (within 200 chars)
        idx = report_text.find(form_id)
        if idx == -1:
            return None
        context = report_text[max(0, idx-50):idx+200]
        # Look for retention year values
        for val in ["10", "5"]:
            if re.search(r'\b' + val + r'\b', context):
                return int(val)
        return None

    retention_correct = 0
    retention_details = []
    for form_id, expected_years in EXPECTED_RECORDS.items():
        found_years = extract_retention_for_form(report, form_id)
        is_correct = found_years == expected_years
        if is_correct:
            retention_correct += 1
        retention_details.append(f"{form_id}: expected={expected_years}yr, found={found_years}yr, ok={is_correct}")

    retention_score = retention_correct / len(EXPECTED_RECORDS)
    checks.append({
        "name": "GJB retention periods correct for all 6 records (5yr vs 10yr distinction)",
        "passed": retention_score >= 0.8,
        "detail": "; ".join(retention_details)
    })
    total_score += retention_score * 0.25

    # ---------------------------------------------------------------
    # CHECK 4: Electrical test thresholds
    # ---------------------------------------------------------------
    elec_checks = {
        "insulation_100": ("绝缘电阻" in report_str or "insulation" in report_str.lower()) and
                          ("100" in report_str),
        "withstand_1500": "1500" in report_str,
        "vibration_2_8": ("2.8" in report_str),
        "noise_65": "65" in report_str,
    }
    elec_passed = sum(1 for v in elec_checks.values() if v)
    checks.append({
        "name": "Electrical test thresholds present (100MΩ, 1500V, 2.8mm/s, 65dB)",
        "passed": elec_passed >= 3,
        "detail": f"Found {elec_passed}/4 thresholds: {elec_checks}"
    })
    if elec_passed >= 3:
        total_score += 0.15

    # ---------------------------------------------------------------
    # CHECK 5: Bearing max heating temperature (≤120°C, NOT 150°C from distractor)
    # ---------------------------------------------------------------
    has_120 = "120" in report_str
    has_150_only = ("150" in report_str) and ("120" not in report_str)
    bearing_temp_ok = has_120 and not has_150_only
    checks.append({
        "name": "Bearing heating temperature correctly stated as ≤120°C (not distractor 150°C)",
        "passed": bearing_temp_ok,
        "detail": f"has_120={has_120}, has_150_only={has_150_only}. Correct value is ≤120°C from SKILL.md."
    })
    if bearing_temp_ok:
        total_score += 0.10

    # ---------------------------------------------------------------
    # CHECK 6: Motor rotor balance grade G2.5 = 2.5mm/s
    # ---------------------------------------------------------------
    has_g25 = "G2.5" in report_str or "2.5" in report_str
    checks.append({
        "name": "Motor rotor balance grade G2.5 / 2.5mm/s referenced",
        "passed": has_g25,
        "detail": f"G2.5 or 2.5mm/s in report: {has_g25}"
    })
    if has_g25:
        total_score += 0.10

    # ---------------------------------------------------------------
    # FINAL SCORING
    # ---------------------------------------------------------------
    # Normalize to 0..1 (max achievable: 0.20+0.20+0.25+0.15+0.10+0.10 = 1.00)
    final_score = min(1.0, total_score)
    overall_passed = final_score >= 0.70

    result = {
        "passed": overall_passed,
        "score": round(final_score, 4),
        "checks": checks
    }
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(json.dumps({"passed": False, "score": 0.0, "checks": [
            {"name": "argument check", "passed": False, "detail": "No workspace path provided."}
        ]}))
        sys.exit(1)
    run_checks(sys.argv[1])