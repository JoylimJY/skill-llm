import sys
import json
import re
from pathlib import Path

def run_eval(workspace: str):
    ws = Path(workspace)
    checks = []
    total_score = 0.0

    # ── Helper ───────────────────────────────────────────────────────────────
    def add_check(name, passed, detail, weight=1.0):
        checks.append({"name": name, "passed": passed, "detail": detail})
        return weight if passed else 0.0

    # ── 1. Find daily_digest.md ───────────────────────────────────────────────
    digest_files = list(ws.rglob("daily_digest.md"))
    if not digest_files:
        checks.append({
            "name": "digest_file_exists",
            "passed": False,
            "detail": "daily_digest.md not found anywhere in workspace"
        })
        print(json.dumps({"passed": False, "score": 0.0, "checks": checks}))
        return

    digest_path = digest_files[0]
    try:
        content = digest_path.read_text(encoding="utf-8")
    except Exception as e:
        checks.append({
            "name": "digest_file_readable",
            "passed": False,
            "detail": f"Could not read daily_digest.md: {e}"
        })
        print(json.dumps({"passed": False, "score": 0.0, "checks": checks}))
        return

    total_score += add_check(
        "digest_file_exists",
        True,
        f"Found daily_digest.md at {digest_path}",
        weight=0.5
    )

    # ── 2. assets/feeds.txt was generated ────────────────────────────────────
    feeds_path = ws / "assets" / "feeds.txt"
    feeds_exists = feeds_path.exists()
    total_score += add_check(
        "feeds_txt_generated",
        feeds_exists,
        "assets/feeds.txt generated by parse_opml.py" if feeds_exists else "assets/feeds.txt missing – parse_opml.py was not run",
        weight=0.5
    )

    if feeds_exists:
        try:
            feeds_content = feeds_path.read_text(encoding="utf-8")
            # Should contain deduplicated feeds (Paul Graham should appear only once)
            pg_count = feeds_content.count("paulgraham.com/rss.xml")
            no_duplicate = pg_count == 1
            total_score += add_check(
                "feeds_deduplication",
                no_duplicate,
                f"Paul Graham RSS appears {pg_count} time(s) in feeds.txt (expected 1, duplicates removed)",
                weight=0.5
            )
            # Should contain MANUAL_SCAN_REQUIRED section
            has_manual = "MANUAL_SCAN_REQUIRED" in feeds_content
            total_score += add_check(
                "feeds_manual_scan_section",
                has_manual,
                "feeds.txt contains ## MANUAL_SCAN_REQUIRED section" if has_manual
                else "feeds.txt missing MANUAL_SCAN_REQUIRED section for WeChat OA entries",
                weight=0.5
            )
            # Should NOT contain entries with empty xmlUrl (虎嗅财经 had empty xmlUrl)
            no_empty_url = "虎嗅" not in feeds_content.split("## MANUAL_SCAN_REQUIRED")[0]
            total_score += add_check(
                "feeds_skips_empty_xmlurl",
                no_empty_url,
                "feeds.txt correctly skips entries with empty xmlUrl" if no_empty_url
                else "feeds.txt incorrectly includes entries with empty xmlUrl",
                weight=0.5
            )
        except Exception as e:
            checks.append({"name": "feeds_txt_parse_error", "passed": False, "detail": str(e)})

    # ── 3. assets/digest_raw.json was generated ───────────────────────────────
    raw_json_path = ws / "assets" / "digest_raw.json"
    raw_exists = raw_json_path.exists()
    total_score += add_check(
        "digest_raw_json_generated",
        raw_exists,
        "assets/digest_raw.json generated by build_digest.py" if raw_exists
        else "assets/digest_raw.json missing – build_digest.py was not run",
        weight=0.5
    )

    raw_data = {}
    if raw_exists:
        try:
            raw_data = json.loads(raw_json_path.read_text(encoding="utf-8"))
        except Exception as e:
            checks.append({"name": "digest_raw_json_parse", "passed": False, "detail": str(e)})

    # ── 4. Keyword merging: 出海 and SaaS should be included ─────────────────
    if raw_data:
        used_keywords = raw_data.get("keywords_used", [])
        has_new_keywords = any(k in used_keywords for k in ["出海", "SaaS", "saas"])
        has_default_keywords = all(
            any(k.lower() == d.lower() for k in used_keywords)
            for d in ["创业", "AI", "增长", "金融"]
        )
        total_score += add_check(
            "keywords_merged_with_defaults",
            has_new_keywords and has_default_keywords,
            f"Keywords used: {used_keywords}. Need defaults + new keywords (出海/SaaS). "
            f"Has new: {has_new_keywords}, Has defaults: {has_default_keywords}",
            weight=1.0
        )

        # Time window filter: item published 55h ago must not appear
        items = raw_data.get("items", [])
        old_item_included = any(
            "窗口外" in i.get("title", "") or i.get("published_hours_ago", 0) > 48
            for i in items
        )
        total_score += add_check(
            "time_window_filter_applied",
            not old_item_included,
            "55h-old item correctly excluded from digest" if not old_item_included
            else "55h-old item incorrectly included (time window filter failed)",
            weight=0.5
        )

        # Noise dropped
        dropped = raw_data.get("dropped_noise", [])
        motivational_dropped = any("motivational" in d.get("reason", "").lower() or
                                   "激励" in d.get("title", "") or
                                   "努力" in d.get("title", "")
                                   for d in dropped)
        repeated_dropped = any("repeated" in d.get("reason", "").lower() or
                               "重复" in d.get("title", "")
                               for d in dropped)
        total_score += add_check(
            "noise_items_dropped",
            motivational_dropped and repeated_dropped,
            f"Noise filter: motivational dropped={motivational_dropped}, repeated-opinion dropped={repeated_dropped}",
            weight=0.5
        )

        # shortlisted cap (max 8)
        shortlisted_count = raw_data.get("shortlisted", 0)
        within_cap = shortlisted_count <= 8
        total_score += add_check(
            "shortlist_cap_respected",
            within_cap,
            f"Shortlisted count={shortlisted_count} (must be ≤8 to keep digest under 10 total)",
            weight=0.3
        )

    # ── 5. daily_digest.md structure checks ──────────────────────────────────
    content_lower = content.lower()

    # Section 1: Top 3 must-read signals
    has_top3 = bool(re.search(
        r"top\s*3|must.read|三.*信号|必读|must.read signals",
        content, re.IGNORECASE
    ))
    total_score += add_check(
        "digest_section_top3_mustread",
        has_top3,
        "Digest contains Top 3 must-read signals section" if has_top3
        else "Digest missing Top 3 must-read signals section",
        weight=1.0
    )

    # Section 2: Top 5 watchlist
    has_watchlist = bool(re.search(
        r"top\s*5|watchlist|观察清单|待观察",
        content, re.IGNORECASE
    ))
    total_score += add_check(
        "digest_section_watchlist",
        has_watchlist,
        "Digest contains Top 5 watchlist section" if has_watchlist
        else "Digest missing Top 5 watchlist section",
        weight=1.0
    )

    # Section 3: Dropped noise summary
    has_noise_summary = bool(re.search(
        r"dropped|noise|过滤|噪音|被.*过滤|filtered",
        content, re.IGNORECASE
    ))
    total_score += add_check(
        "digest_section_dropped_noise",
        has_noise_summary,
        "Digest contains dropped noise summary" if has_noise_summary
        else "Digest missing dropped noise summary section",
        weight=1.0
    )

    # Section 4: Filter transparency with pipeline counts
    # Must have format like: scanned -> matched -> shortlisted -> top3
    # OR contain numerical counts for all 4 stages
    has_pipeline = bool(re.search(
        r"scanned.*matched.*shortlisted|扫描.*匹配.*入围|scan.*match.*shortlist",
        content, re.IGNORECASE
    ))
    has_counts = bool(re.search(
        r"\bscanned\b.*\d+|\b扫描\b.*\d+",
        content, re.IGNORECASE
    ))
    has_rates = bool(re.search(
        r"\d+\s*%|\d+\s*/\s*\d+",
        content
    ))
    transparency_ok = has_pipeline and (has_counts or has_rates)
    total_score += add_check(
        "digest_section_filter_transparency",
        transparency_ok,
        f"Filter transparency: pipeline_format={has_pipeline}, counts_present={has_counts}, rates_present={has_rates}",
        weight=1.0
    )

    # Section 5: Next experiment
    has_next_experiment = bool(re.search(
        r"next experiment|下一步实验|next.*move|concrete.*action|实验|下一个实验",
        content, re.IGNORECASE
    ))
    total_score += add_check(
        "digest_section_next_experiment",
        has_next_experiment,
        "Digest contains Next experiment section" if has_next_experiment
        else "Digest missing Next experiment section",
        weight=1.0
    )

    # Source links present (clickable)
    has_links = bool(re.search(r"https?://\S+", content))
    total_score += add_check(
        "digest_contains_source_links",
        has_links,
        "Digest contains clickable source links" if has_links
        else "Digest missing clickable source links",
        weight=0.5
    )

    # Manual scan required mentioned for WeChat OA
    has_manual_scan = bool(re.search(
        r"manual scan required|手动扫描|人工查看|manual.*scan",
        content, re.IGNORECASE
    ))
    total_score += add_check(
        "digest_manual_scan_noted",
        has_manual_scan,
        "Digest notes manual scan required for no-RSS sources" if has_manual_scan
        else "Digest missing manual scan required notation for WeChat OA / no-RSS sources",
        weight=0.5
    )

    # Must NOT include motivational noise in top items
    motivational_in_digest = bool(re.search(
        r"努力就会成功|坚持下去创业路|你不孤单.*创业|generic motivational",
        content
    ))
    total_score += add_check(
        "digest_excludes_noise_items",
        not motivational_in_digest,
        "Digest correctly excludes motivational noise items" if not motivational_in_digest
        else "Digest incorrectly includes a motivational noise item in the output",
        weight=1.0
    )

    # Total items under 10
    # Count bullet points / numbered items in top3 + watchlist sections
    listed_items = re.findall(r"^\s*[-*•]\s+|\d+\.\s+", content, re.MULTILINE)
    # A rough proxy: not more than 20 bullet-style lines (generous to handle sub-bullets)
    reasonable_count = len(listed_items) <= 40
    total_score += add_check(
        "digest_reasonable_length",
        reasonable_count,
        f"Digest has {len(listed_items)} list items (should not be bloated beyond 10 main items)",
        weight=0.3
    )

    # ── Final scoring ─────────────────────────────────────────────────────────
    max_score = sum([
        0.5,   # file exists
        0.5,   # feeds.txt
        0.5,   # dedup
        0.5,   # manual scan section
        0.5,   # skip empty xmlUrl
        0.5,   # digest_raw.json
        1.0,   # keyword merge
        0.5,   # time window
        0.5,   # noise dropped
        0.3,   # shortlist cap
        1.0,   # top3
        1.0,   # watchlist
        1.0,   # noise summary
        1.0,   # transparency
        1.0,   # next experiment
        0.5,   # links
        0.5,   # manual scan noted
        1.0,   # excludes noise
        0.3,   # reasonable length
    ])
    normalized = round(min(total_score / max_score, 1.0), 4)
    all_critical_passed = all(
        c["passed"] for c in checks
        if c["name"] in {
            "digest_file_exists",
            "digest_section_top3_mustread",
            "digest_section_watchlist",
            "digest_section_dropped_noise",
            "digest_section_filter_transparency",
            "digest_section_next_experiment",
            "digest_excludes_noise_items",
            "keywords_merged_with_defaults",
        }
    )

    print(json.dumps({
        "passed": all_critical_passed and normalized >= 0.70,
        "score": normalized,
        "checks": checks
    }, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    workspace_dir = sys.argv[1] if len(sys.argv) > 1 else "/workspace"
    run_eval(workspace_dir)